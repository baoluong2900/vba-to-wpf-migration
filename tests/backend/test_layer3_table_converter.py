"""Access schema → DDL (src/backend/workflow/layer3/sql_migration/table_converter.py)."""
from __future__ import annotations

import pytest

from layer3.sql_migration.table_converter import (
    canonical_access_type,
    column_type,
    convert_table_to_ddl,
    quote_identifier,
)

USERS = {
    "table_name": "TBL_Users",
    "columns": [
        {"logical_name": "ID", "data_type": "Long", "length": "4", "required": "True"},
        {"logical_name": "Name", "data_type": "Text", "length": "50", "required": "True"},
        {"logical_name": "Age", "data_type": "Integer", "length": "2", "required": "False"},
        {"logical_name": "LoginTime", "data_type": "Date/Time", "length": "8", "required": "False"},
        {"logical_name": "IsActive", "data_type": "Boolean", "length": "1", "required": "False"},
    ],
}


def test_postgresql_ddl_for_the_fixture_table():
    assert convert_table_to_ddl(USERS, "PostgreSQL") == (
        "CREATE TABLE TBL_Users (\n"
        "    ID BIGINT NOT NULL,\n"
        "    Name VARCHAR(50) NOT NULL,\n"
        "    Age INTEGER,\n"
        "    LoginTime TIMESTAMP,\n"
        "    IsActive BOOLEAN\n"
        ");"
    )


@pytest.mark.parametrize(
    ("access_type", "expected"),
    [
        ("Text", "VARCHAR(255)"),
        ("Short Text", "VARCHAR(255)"),
        ("Memo", "TEXT"),
        ("Long Text", "TEXT"),          # used to match "text" first → VARCHAR(255)
        ("Hyperlink", "TEXT"),
        ("LongBinary", "BYTEA"),        # used to match "long" first → BIGINT
        ("OLE Object", "BYTEA"),
        ("AutoNumber", "INTEGER GENERATED BY DEFAULT AS IDENTITY"),  # used to fall back to VARCHAR
        ("Counter", "INTEGER GENERATED BY DEFAULT AS IDENTITY"),
        ("Long", "BIGINT"),
        ("Long Integer", "BIGINT"),
        ("Integer", "INTEGER"),
        ("Byte", "SMALLINT"),
        ("BigInt", "BIGINT"),
        ("Single", "DOUBLE PRECISION"),
        ("Double", "DOUBLE PRECISION"),
        ("Decimal", "NUMERIC"),
        ("Currency", "NUMERIC(19, 4)"),
        ("Date/Time", "TIMESTAMP"),
        ("Yes/No", "BOOLEAN"),
        ("Boolean", "BOOLEAN"),
        ("GUID", "UUID"),
        ("Replication ID", "UUID"),
        ("SomethingNew", "VARCHAR(255)"),
    ],
)
def test_postgresql_type_mapping(access_type, expected):
    assert column_type({"data_type": access_type}, "PostgreSQL") == expected


@pytest.mark.parametrize(
    ("dialect", "text", "memo", "auto"),
    [
        ("SQL Server", "NVARCHAR(20)", "NVARCHAR(MAX)", "INT IDENTITY(1,1)"),
        ("MySQL", "VARCHAR(20)", "LONGTEXT", "INT AUTO_INCREMENT"),
        ("Oracle", "VARCHAR(20)", "CLOB", "INTEGER"),  # unknown dialect → ANSI
    ],
)
def test_other_dialects(dialect, text, memo, auto):
    assert column_type({"data_type": "Text", "length": "20"}, dialect) == text
    assert column_type({"data_type": "Memo"}, dialect) == memo
    assert column_type({"data_type": "AutoNumber"}, dialect) == auto


@pytest.mark.parametrize("length", ["", "0", "abc", None, "-5"])
def test_bad_text_length_falls_back_to_255(length):
    assert column_type({"data_type": "Text", "length": length}, "PostgreSQL") == "VARCHAR(255)"


def test_plain_identifiers_stay_unquoted():
    # Unquoted names keep PostgreSQL's lower-case folding, which generated code relies on.
    assert quote_identifier("TBL_Users") == "TBL_Users"
    assert quote_identifier("T023地区CD設定") == "T023地区CD設定"
    assert quote_identifier("_tmp1") == "_tmp1"


@pytest.mark.parametrize(
    ("name", "dialect", "expected"),
    [
        ("Order Date", "PostgreSQL", '"Order Date"'),
        ("user", "PostgreSQL", '"user"'),
        ("Order", "PostgreSQL", '"Order"'),
        ("1stCol", "PostgreSQL", '"1stCol"'),
        ('we"ird', "PostgreSQL", '"we""ird"'),
        ("Order Date", "SQL Server", "[Order Date]"),
        ("a]b", "SQL Server", "[a]]b]"),
        ("Order Date", "MySQL", "`Order Date`"),
    ],
)
def test_identifiers_that_need_quoting(name, dialect, expected):
    assert quote_identifier(name, dialect) == expected


def test_injection_through_a_column_name_is_neutralised():
    table = {"table_name": "t", "columns": [{"logical_name": "x INT); DROP TABLE users; --", "data_type": "Text"}]}
    ddl = convert_table_to_ddl(table, "PostgreSQL")
    assert '"x INT); DROP TABLE users; --" VARCHAR(255)' in ddl


def test_primary_key_constraint():
    table = {
        "table_name": "Orders",
        "columns": [
            {"logical_name": "OrderID", "data_type": "AutoNumber", "required": "True", "primary_key": True},
            {"logical_name": "Total", "data_type": "Currency"},
        ],
    }
    assert convert_table_to_ddl(table, "PostgreSQL").endswith("    PRIMARY KEY (OrderID)\n);")


def test_required_accepts_access_true_values():
    for value in ("True", "true", "-1", "Yes", True):
        assert "NOT NULL" in convert_table_to_ddl(
            {"table_name": "t", "columns": [{"logical_name": "c", "data_type": "Text", "required": value}]},
            "PostgreSQL",
        )


def test_table_without_columns_is_an_error():
    with pytest.raises(ValueError):
        convert_table_to_ddl({"table_name": "Empty", "columns": []}, "PostgreSQL")


def test_canonical_type_is_case_and_separator_insensitive():
    assert canonical_access_type("date / time") == canonical_access_type("DATETIME") == "datetime"
