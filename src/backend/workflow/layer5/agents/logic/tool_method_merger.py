"""
agents/logic/tool_method_merger.py — Deterministic Method Merger

Merge partial C# method outputs (from per-event LLM calls) into
a complete ViewModel class. Zero LLM token for the merge step.

Ref: Agent_Logic.md — "Merge (Roslyn AST)" section
Ref: agents/ui/tool_skeleton.py — same deterministic gen pattern
"""
from __future__ import annotations

import logging
import re
from typing import Any

logger = logging.getLogger(__name__)


class MethodMerger:
    """
    Merge multiple C# method bodies into a complete ViewModel class.
    Deterministic — zero LLM token cost.
    """

    def merge(
        self,
        form_name: str,
        method_outputs: list[dict],
        vm_bindings: dict | None = None,
        service_name: str = "",
        sys_methods: list[dict] | None = None,
        all_chunks: list[dict] | None = None,
        vm_class: str | None = None,
    ) -> str:
        """
        Merge partial method outputs into a complete ViewModel .cs file.

        Args:
            form_name: e.g. "F_Login"
            method_outputs: list of dicts from LLM calls:
                [{"event_id": "E003", "cs_method": "LoginAsync", "code": "..."}]
            vm_bindings: {properties: [...], commands: [...]}
            service_name: e.g. "Auth" → IAuthService
            sys_methods: SYS-type methods to include (deterministic stubs)
            all_chunks: Full list of all event chunks
            vm_class: Optional override for the generated ViewModel class name

        Returns:
            Complete C# ViewModel code string
        """
        vm_class = vm_class or self._form_to_vm_class(form_name)
        bindings = vm_bindings or {"properties": [], "commands": []}

        # ── Using statements ──────────────────────────────────────────
        usings = self._build_usings(method_outputs, service_name)

        # ── Service field + constructor injection ──────────────────────
        service_block = self._build_service_injection(service_name)

        # ── Properties ────────────────────────────────────────────────
        props_block = self._build_properties(bindings.get("properties", []))

        # ── Commands ──────────────────────────────────────────────────
        commands = bindings.get("commands", [])
        cmd_declarations = self._build_command_declarations(commands)
        cmd_init = self._build_command_initializations(commands, method_outputs)

        # ── Constructor ───────────────────────────────────────────────
        constructor = self._build_constructor(
            vm_class, service_name, cmd_init,
            method_outputs, sys_methods,
        )

        # ── Method bodies (from LLM) ─────────────────────────────────
        methods_block = self._build_methods(method_outputs)

        # ── SYS method stubs ──────────────────────────────────────────
        sys_block = self._build_sys_methods(sys_methods or [])

        # ── Deferred/Stub methods ─────────────────────────────────────
        stub_methods_block = self._build_deferred_stubs(all_chunks, method_outputs, sys_methods)

        # ── Assemble ──────────────────────────────────────────────────
        code = f"""{usings}
namespace vba_brain.UI.WPF.ViewModels;

/// <summary>
/// {form_name} ViewModel — Auto-generated by Agent Logic.
/// LLM-generated methods merged with deterministic skeleton.
/// </summary>
public class {vm_class} : ViewModelBase
{{
{service_block}
{props_block}
{cmd_declarations}
{constructor}
{methods_block}
{sys_block}
{stub_methods_block}}}
"""
        # Clean up excessive blank lines
        code = re.sub(r'\n{3,}', '\n\n', code)

        # Convert the merged WPF ViewModel → Avalonia (namespaces, usings,
        # MessageBox.Show → Debug.WriteLine, KeyEventArgs, event names).
        try:
            from pipeline.avalonia_cs import to_avalonia_cs
            code = to_avalonia_cs(code)
        except Exception:  # pragma: no cover - defensive
            pass

        logger.info(
            "[MethodMerger] Merged %d methods + %d SYS stubs → %s (%d lines)",
            len(method_outputs), len(sys_methods or []),
            f"{vm_class}.cs", code.count('\n'),
        )
        return code

    # ──────────────────────────────────────────
    # Build blocks
    # ──────────────────────────────────────────

    def _build_usings(self, method_outputs: list[dict], service_name: str) -> str:
        """Generate using statements based on what the ViewModel needs."""
        usings = [
            "using System;",
            "using System.Threading.Tasks;",
            "using System.Windows;",
            "using System.Windows.Controls;",
            "using System.Windows.Input;",
            "using vba_brain.UI.WPF.Utils;",
        ]

        # Only add service namespace if the interface actually exists in the project.
        # DO NOT add vba_brain.Services — this namespace may not exist yet.
        # Service interface using directives are added by Agent Service, not here.
        if service_name:
            usings.extend([
                "using vba_brain.Application.Interfaces;",
                "using vba_brain.Application.DTOs.Requests;",
                "using vba_brain.Application.DTOs.Responses;",
            ])

        # Scan method bodies for additional using hints
        all_code = " ".join(m.get("code", "") for m in method_outputs)
        if "DispatcherTimer" in all_code:
            usings.append("using System.Windows.Threading;")
        if "ObservableCollection" in all_code:
            usings.append("using System.Collections.ObjectModel;")

        return "\n".join(sorted(set(usings)))

    def _build_service_injection(self, service_name: str) -> str:
        """Generate private readonly service field.
        
        NOTE: Only inject service when Agent Service has already generated
        the interface. For UI-only runs, service_name should be empty.
        """
        if not service_name:
            return ""
        field_name = self._to_field_name(service_name, is_service=True)
        # Use fully-qualified type to avoid namespace conflicts
        return f"    private readonly vba_brain.Application.Interfaces.I{service_name}Service {field_name};\n"

    def _build_properties(self, properties: list[str]) -> str:
        """Generate property declarations with INotifyPropertyChanged pattern."""
        if not properties:
            return ""

        from agents.logic.mapping_ast.event_mapper import EventMapper
        
        lines = ["    // ── Properties (from XAML bindings) ──────────────────"]
        for prop in properties:
            safe_prop = EventMapper._sanitize_method_name(prop)
            field = self._to_field_name(safe_prop)
            cs_type = self._infer_type(prop)
            default = self._default_value(cs_type)
            lines.extend([
                f"    private {cs_type} {field} = {default};",
                f"    public {cs_type} {safe_prop}",
                "    {",
                f"        get => {field};",
                f"        set {{ {field} = value; OnPropertyChanged(); }}",
                "    }",
                "",
            ])
        return "\n".join(lines)

    def _build_command_declarations(self, commands: list[str]) -> str:
        """Generate ICommand property declarations."""
        if not commands:
            return ""

        from agents.logic.mapping_ast.event_mapper import EventMapper
        
        lines = ["    // ── Commands ──────────────────────────────────────────"]
        for cmd in commands:
            safe_cmd = EventMapper._sanitize_method_name(cmd)
            lines.append(f"    public ICommand {safe_cmd} {{ get; set; }} = default!;")
        lines.append("")
        return "\n".join(lines)

    def _build_command_initializations(
        self,
        commands: list[str],
        method_outputs: list[dict],
    ) -> str:
        """Generate command = new RelayCommand(...) lines for constructor."""
        if not commands:
            return ""

        # Build method lookup: command name → method name
        cmd_method_map: dict[str, str] = {}
        for m in method_outputs:
            cmd = m.get("mapped_command", {}).get("cs_command", "")
            method = m.get("cs_method", "") or m.get("mapped_command", {}).get("cs_method", "")
            if cmd and method:
                cmd_method_map[cmd] = method

        from agents.logic.mapping_ast.event_mapper import EventMapper
        
        lines = []
        for cmd in commands:
            safe_cmd = EventMapper._sanitize_method_name(cmd)
            method = cmd_method_map.get(cmd)
            if method:
                # Detect if method is async
                is_async = method.endswith("Async")
                if is_async:
                    lines.append(
                        f"        {safe_cmd} = Cmd(async o => await {method}(o));"
                    )
                else:
                    lines.append(
                        f"        {safe_cmd} = Cmd(() => {method}());"
                    )
            else:
                # No matching method → stub
                lines.append(
                    f"        {safe_cmd} = Cmd(() => {{ /* TODO: implement */ }});"
                )
        return "\n".join(lines)

    def _build_constructor(
        self,
        vm_class: str,
        service_name: str,
        cmd_init: str,
        method_outputs: list[dict],
        sys_methods: list[dict] | None,
    ) -> str:
        """Generate constructor with DI and command initialization."""
        # Constructor parameters
        params = []
        body_lines = []

        if service_name:
            field_name = self._to_field_name(service_name, is_service=True)
            params.append(f"I{service_name}Service {service_name.lower()}Service")
            body_lines.append(f"        {field_name} = {service_name.lower()}Service;")

        # Add SYS init code (Form_Open → constructor logic)
        if sys_methods:
            for sm in sys_methods:
                if sm.get("mapped_command", {}).get("vba_event", "").lower() in ("form_open",):
                    init_code = sm.get("init_code", "")
                    if init_code:
                        body_lines.append(f"\n        // Form_Open init")
                        body_lines.append(f"        {init_code}")

        # Command init
        if cmd_init:
            body_lines.append("")
            body_lines.append("        // Command bindings")
            body_lines.append(cmd_init)

        params_str = ", ".join(params)
        body_str = "\n".join(body_lines)

        return f"""    // ── Constructor ─────────────────────────────────────────
    public {vm_class}({params_str})
    {{
{body_str}
    }}
"""

    def _build_methods(self, method_outputs: list[dict]) -> str:
        """Insert LLM-generated method bodies."""
        if not method_outputs:
            return ""

        lines = ["    // ── Methods (LLM-generated from BD events + DD steps) ──"]

        for m in method_outputs:
            event_id  = m.get("event_id", "")
            vba_event = m.get("mapped_command", {}).get("vba_event", "")
            code      = m.get("code", "").strip()

            if not code:
                continue

            # Add event annotation comment
            lines.append(f"\n    // {event_id}: {vba_event}")

            # Indent and insert method code
            # If code already has method signature → insert as-is
            # If code is just body → wrap in method
            if self._has_method_signature(code):
                # Ensure proper indentation (4 spaces)
                indented = self._indent(code, spaces=4)
                lines.append(indented)
            else:
                # Wrap in method with signature from mapped_command
                method_name = m.get("cs_method", "") or m.get("mapped_command", {}).get("cs_method", "")
                if method_name:
                    is_async = method_name.endswith("Async")
                    if is_async:
                        lines.append(f"    private async Task {method_name}(object? parameter)")
                        lines.append("    {")
                    else:
                        lines.append(f"    private void {method_name}()")
                        lines.append("    {")
                    indented = self._indent(code, spaces=8)
                    lines.append(indented)
                    lines.append("    }")

        lines.append("")
        return "\n".join(lines)

    def _build_sys_methods(self, sys_methods: list[dict]) -> str:
        """Generate deterministic stubs for SYS-type events."""
        if not sys_methods:
            return ""

        lines = ["    // ── SYS Methods (deterministic stubs) ──────────────────"]
        seen_methods = set()

        for sm in sys_methods:
            mapped     = sm.get("mapped_command", {})
            vba_event  = mapped.get("vba_event", "")
            cs_method  = mapped.get("cs_method", "")
            module_id  = mapped.get("module_id", sm.get("bd_event", {}).get("module_id", ""))
            action_type = mapped.get("action_type", "SYS")

            if not cs_method or vba_event.lower() == "form_open":
                continue  # Form_Open handled in constructor

            # Skip 参照マクロ events — they use F-ID methods already in ui_event_map
            # gen_viewmodel handles them; no separate SYS stub needed here
            if mapped.get("macro_ref") or vba_event.startswith("参照マクロ"):
                continue

            # Use module_id-based name if cs_method contains Japanese or non-ASCII
            if any(ord(c) > 127 for c in cs_method):
                if module_id:
                    cs_method = f"{module_id}Async"
                else:
                    continue  # Skip — cannot gen valid C# identifier

            if cs_method in seen_methods:
                logger.info("[MethodMerger] Skipping duplicate SYS method stub: %s", cs_method)
                continue
            seen_methods.add(cs_method)

            lines.append(f"\n    // {vba_event} → {cs_method} ({action_type})")

            # Generate stub based on event type
            is_close = "close" in cs_method.lower() or "閉じる" in vba_event
            if is_close:
                # Avoid name collision with Window.Close() — use OnClose prefix
                safe_name = f"On{cs_method}" if cs_method.lower() == "close" else cs_method
                lines.extend([
                    f"    private void {safe_name}()",
                    "    {",
                    "        System.Windows.Application.Current.Shutdown();",
                    "    }",
                ])
            elif "timer" in cs_method.lower():
                lines.extend([
                    f"    private void {cs_method}()",
                    "    {",
                    "        // TODO: implement timer logic",
                    "    }",
                ])
            else:
                lines.extend([
                    f"    private void {cs_method}()",
                    "    {",
                    f"        // TODO: implement {vba_event}",
                    "    }",
                ])

        lines.append("")
        return "\n".join(lines)

    # ──────────────────────────────────────────
    # Helpers
    # ──────────────────────────────────────────

    @staticmethod
    def _form_to_vm_class(form_name: str) -> str:
        """Keep original name: F_Login → F_Login"""
        return re.sub(r'[^\w]', '', form_name)

    @staticmethod
    def _to_field_name(name: str, is_service: bool = False) -> str:
        """Convert property/service name to private field name."""
        if not name:
            return "_field"
        # Already a field name
        if name.startswith("_"):
            return name
            
        camel_case = f"_{name[0].lower()}{name[1:]}" if name[0].isupper() else f"_{name}"
        
        # Service name → _authService
        if is_service and not name.endswith("Service"):
            return f"{camel_case}Service"
            
        return camel_case

    @staticmethod
    def _infer_type(prop_name: str) -> str:
        """Infer C# type from property name."""
        lower = prop_name.lower()
        if any(kw in lower for kw in ("is_", "has_", "can_", "show_", "visible")):
            return "bool"
        if any(kw in lower for kw in ("count", "index", "number", "num", "id")):
            return "int"
        if "date" in lower:
            return "DateTime?"
        if "list" in lower or "items" in lower:
            return "ObservableCollection<object>"
        return "string"

    @staticmethod
    def _default_value(cs_type: str) -> str:
        """Get default value for C# type."""
        if cs_type == "bool":
            return "false"
        if cs_type == "int":
            return "0"
        if cs_type.startswith("DateTime"):
            return "null"
        if "Collection" in cs_type:
            return "new()"
        return "string.Empty"

    @staticmethod
    def _has_method_signature(code: str) -> bool:
        """Check if code contains a C# method signature."""
        return bool(re.search(
            r'(private|public|internal|protected)\s+(static\s+)?(async\s+)?(void|Task|string|int|bool)',
            code
        ))

    @staticmethod
    def _indent(code: str, spaces: int = 4) -> str:
        """Indent all lines of code by given spaces."""
        prefix = " " * spaces
        lines = code.split("\n")
        return "\n".join(
            f"{prefix}{line}" if line.strip() else line
            for line in lines
        )

    def _build_deferred_stubs(
        self,
        all_chunks: list[dict] | None,
        method_outputs: list[dict],
        sys_methods: list[dict] | None,
    ) -> str:
        """Generate virtual async stubs for deferred/ungenerated events to ensure successful compilation."""
        if not all_chunks:
            return ""

        from agents.logic.mapping_ast.event_mapper import EventMapper

        generated_names = set()
        for m in method_outputs:
            name = m.get("cs_method") or m.get("mapped_command", {}).get("cs_method")
            if name:
                generated_names.add(EventMapper._sanitize_method_name(name))

        sys_names = set()
        if sys_methods:
            for sm in sys_methods:
                name = sm.get("mapped_command", {}).get("cs_method")
                if name:
                    sys_names.add(EventMapper._sanitize_method_name(name))

        lines = ["    // ── Deferred / Stub Methods (Ensures Successful Compilation) ──"]
        generated_any = False

        for c in all_chunks:
            mapped = c.get("mapped_command", {})
            if not mapped.get("is_main_logic"):
                continue

            cs_method = mapped.get("cs_method") or (c.get("bd_event", {}).get("notes", "") + "Async")
            if not cs_method:
                continue

            safe_method = EventMapper._sanitize_method_name(cs_method)
            if safe_method in generated_names or safe_method in sys_names:
                continue

            vba_event = mapped.get("vba_event", "")
            event_id = c.get("bd_event", {}).get("event_id", "")
            event_class = c.get("event_class", "")

            lines.append(
                f"\n    /// <summary>\n"
                f"    /// {event_id}: VBA: {vba_event} ({event_class}) — Deferred event stub to prevent compile errors.\n"
                f"    /// </summary>\n"
                f"    public virtual async System.Threading.Tasks.Task {safe_method}()\n"
                f"    {{\n"
                f"        await System.Threading.Tasks.Task.CompletedTask;\n"
                f"    }}"
            )
            generated_any = True

        if not generated_any:
            return ""
        lines.append("")
        return "\n".join(lines)
