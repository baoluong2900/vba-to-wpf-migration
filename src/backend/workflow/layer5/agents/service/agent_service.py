    def _save_service_contract(
        self,
        form_name: str,
        feature: str,
        service_input: dict,
        files: list[GeneratedFile],
    ) -> Path:
        """
        Save service_contract.json — single source of truth for downstream agents.

        Schema:
        {
          "form_name":     "F_Login",
          "feature":       "FLogin",
          "service_class": "FLoginService",
          "iface_class":   "IFLoginService",
          "service_field": "_fLoginService",   // DI field name in ViewModel
          "namespace":     "vba_brain.Application.Services",
          "methods": {
            "F000": {
              "method_name":     "F000Async",
              "return_type":     "Task<F000Response>",
              "request_class":   "F000Request",
              "response_class":  "F000Response",
              "request_props":   [{"name": "TxtID", "type": "string"}],
              "event_trigger":   "画面を開く時",
              "event_content":   "...",
              "vm_method_name":  "F000Async"   // mirrors ui_event_map
            },
            ...
          }
        }
        """
        import re as _re

        service_name = f"{feature}Service"
        iface_name = f"I{service_name}"
        # DI field name: IFLoginService → _fLoginService
        svc_field = "_" + service_name[0].lower() + service_name[1:]

        # Parse request properties from generated Request DTO content
        req_file_content = next(
            (f.content for f in files if "Requests" in f.path and f.path.endswith(".cs")),
            "",
        )
        # Parse response properties from generated Response DTO content
        res_file_content = next(
            (f.content for f in files if "Responses" in f.path and f.path.endswith(".cs")),
            "",
        )

        # Build {Classname → [{name, type}]} from Request DTO
        req_class_props: dict[str, list[dict]] = {}
        if req_file_content:
            current_cls = None
            for line in req_file_content.splitlines():
                cls_m = _re.match(r'\s*public\s+class\s+(\w+Request)', line)
                if cls_m:
                    current_cls = cls_m.group(1)
                    req_class_props[current_cls] = []
                elif current_cls:
                    prop_m = _re.match(
                        r'\s*public\s+([\w<>?\[\]]+)\s+(\w+)\s*\{\s*get;\s*set;\s*\}', line
                    )
                    if prop_m:
                        req_class_props[current_cls].append(
                            {"name": prop_m.group(2), "type": prop_m.group(1)}
                        )

        # Build {Classname → [{name, type}]} from Response DTO
        res_class_props: dict[str, list[dict]] = {}
        if res_file_content:
            current_cls = None
            for line in res_file_content.splitlines():
                cls_m = _re.match(r'\s*public\s+class\s+(\w+Response)', line)
                if cls_m:
                    current_cls = cls_m.group(1)
                    res_class_props[current_cls] = []
                elif current_cls:
                    prop_m = _re.match(
                        r'\s*public\s+([\w<>?\[\].,\s]+?)\s+(\w+)\s*\{\s*get;\s*set;\s*\}', line
                    )
                    if prop_m:
                        res_class_props[current_cls].append(
                            {"name": prop_m.group(2), "type": prop_m.group(1).strip()}
                        )

        # Load ui_event_map for vm_method_name cross-reference
        _ui_map_path = AGENT_DIR.parent / "ui" / "configs" / "ui_event_map.json"
        ui_event_map: dict[str, dict] = {}
        if _ui_map_path.exists():
            try:
                _registry = json.loads(_ui_map_path.read_text(encoding="utf-8"))
                ui_event_map = _registry.get(form_name, {})
            except Exception:
                pass

        # ── Load name_config.json for JP→EN field name translation ──────────
        _name_config_path = (
            Path(__file__).resolve().parent.parent / "repo" / "config" / "name_config.json"
        )
        _field_map: dict[str, str] = {}
        _param_map_cfg: dict[str, str] = {}
        if _name_config_path.exists():
            try:
                _nc = json.loads(_name_config_path.read_text(encoding="utf-8"))
                _field_map = _nc.get("field_name", {})
                _param_map_cfg = _nc.get("parameter_name", {})
            except Exception:
                pass

        def _translate_prop_name(jp_name: str) -> str:
            """Translate JP field/control/param name → EN using name_config.
            Checks field_name first, then parameter_name.
            If not found → return 'TODO' (no _jp suffix).
            Already-ASCII names are returned as-is (PascalCase).
            """
            if not jp_name:
                return "TODO"
            # Already ASCII → keep
            if jp_name.isascii():
                return jp_name[0].upper() + jp_name[1:] if jp_name else jp_name
            # Check field_name map
            en = _field_map.get(jp_name, "")
            if en and not en.startswith("TODO") and en != "":
                return en[0].upper() + en[1:]
            # Check parameter_name map
            en = _param_map_cfg.get(jp_name, "")
            if en and not en.startswith("TODO") and en != "":
                return en[0].upper() + en[1:]
            return "TODO"

        def _translate_props(props: list[dict]) -> list[dict]:
            """Translate name field in each prop dict; keep name_jp only when TODO."""
            result = []
            for p in props:
                orig = p.get("name", "")
                translated = _translate_prop_name(orig)
                entry: dict = {"name": translated, "type": p.get("type", "string")}
                if translated == "TODO":
                    entry["name_jp"] = orig
                result.append(entry)
            return result

        # ── Load repository_contracts từ agent_repo output (nếu có) ─────────
        # Must load BEFORE the methods loop so repo_calls can be resolved
        _repo_output_path = AGENT_DIR.parent / "repo" / "outputs" / f"{form_name}.json"
        _repo_contracts: dict = {}
        if _repo_output_path.exists():
            try:
                _repo_contracts = json.loads(_repo_output_path.read_text(encoding="utf-8"))
            except Exception:
                pass

        # Build methods map from service_input events
        methods: dict[str, dict] = {}
        for idx, ev in enumerate(service_input.get("events", [])):
            mid = ev.get("module_id", "")
            if not mid:
                continue

            # ── Normalize module_id ──────────────────────────────────────────
            # Reports/macros set module_id = form_name (JP name) instead of
            # a slot ID like F000/E001. Normalize to a stable slot key so
            # downstream agents (Logic, UI) can reliably look up the method.
            # Pattern: use F{idx:03d} for the first event, E{idx:03d} for rest.
            if mid == form_name or (len(mid) > 4 and not mid[:1].isalpha() or
                                    not mid[1:].replace('_', '').isalnum()):
                # Only normalize if it looks like a JP name (not already F000/E001 style)
                import re as _re
                _slot_pattern = _re.compile(r'^[A-Z]\d{3}$')
                if not _slot_pattern.match(mid):
                    mid_key = f"F{idx:03d}" if idx == 0 else f"E{idx:03d}"
                    logger.info(
                        "[Agent Service] Normalizing module_id %r → %r for contract",
                        mid, mid_key,
                    )
                    mid = mid_key
            # ────────────────────────────────────────────────────────────────
            from agents.service.tool_service_gen import derive_method_name, _safe_class_token, resolve_repo_for_mapping, build_repo_index, generate_method
            method_name = derive_method_name(ev, feature, form_name)

            # DTO class names — use EN feature-based name (same as what tool_service_gen generates)
            orig_mid = ev.get("module_id", "")
            _cls_token = _safe_class_token(orig_mid, feature)   # EN class prefix (e.g. "R005WorkRequest")
            req_class = f"{_cls_token}Request"
            res_class = f"{_cls_token}Response"
            props = req_class_props.get(req_class, [])
            res_props = res_class_props.get(res_class, [])

            # Translate JP names → EN; fallback to "TODO" if not in name_config
            props = _translate_props(props)

            # ── Build repo_calls + method_code for this method ───────────────
            repo_calls: list[dict] = []
            method_code: str = ""
            try:
                # build_repo_index expects "repositories" key (plural)
                _repo_list = _repo_contracts.get("repository", [])
                _by_query, _by_sheet = build_repo_index({"repositories": _repo_list})

                # repo_calls: which repo function each query_mapping resolves to
                for qm in ev.get("query_mappings") or []:
                    info = resolve_repo_for_mapping(qm, _by_query, _by_sheet)
                    if info:
                        repo_calls.append({
                            "repository": info.get("repo_name", ""),
                            "function":   info.get("function_name", ""),
                            "query":      qm.get("logic_query_name") or qm.get("sheet_name", ""),
                        })

                # method_code: actual C# method body (same as what's in Service.cs)
                _method_src, _ = generate_method(
                    ev, feature, _by_query, _by_sheet, form_name=form_name,
                )
                method_code = _method_src
            except Exception as _rce:
                logger.warning("[Agent Service] repo_calls/method_code build failed: %s", _rce)

            # vm_method_name: từ ui_event_map nếu có, fallback = method_name
            vm_entry = ui_event_map.get(mid, {})
            vm_method = vm_entry.get("vm_method_name") or method_name

            methods[mid] = {
                "method_name":    method_name,
                "return_type":    f"Task<{res_class}>",
                "request_class":  req_class,
                "response_class": res_class,
                "request_props":  props,
                "response_props": res_props,
                "repo_calls":     repo_calls,
                "method_code":    method_code,   # ← C# method body (same as in Service.cs)
                "event_trigger":  ev.get("event_trigger", ""),
                "event_content":  (ev.get("event_content") or "")[:200],
                "vm_method_name": vm_method,
            }

        contract = {
            "form_name":           form_name,
            "feature":             feature,
            "service_class":       service_name,
            "iface_class":         iface_name,
            "service_field":       svc_field,
            "namespace":           "vba_brain.Application.Services",
            "methods":             methods,
            # Repo method mapping — just the repository functions used, no dto/entity bloat
            "repository":          _repo_contracts.get("repository", []),
        }

        # ── Save as {form_name}.json (original JP name — readable, matches form name) ──
        contract_path = OUTPUTS_DIR / form_name / f"{form_name}.json"
        contract_path.parent.mkdir(parents=True, exist_ok=True)
        contract_json = json.dumps(contract, ensure_ascii=False, indent=2)
        contract_path.write_text(contract_json, encoding="utf-8")
        logger.info("[Agent Service] contract saved → %s", contract_path)

        # ── Backup to database_json/agent_service/ ──────────────────────────
        try:
            from pathlib import Path as _Path
            _backup_dir = _Path(__file__).resolve().parent.parent.parent.parent.parent.parent.parent \
                          / "data/database_json" / "agent_service"
            _backup_dir.mkdir(parents=True, exist_ok=True)
            _backup_file = _backup_dir / f"{form_name}.json"
            _backup_file.write_text(
                json.dumps(contract, ensure_ascii=False, indent=2), encoding="utf-8"
            )
            logger.info("[Agent Service] Backup saved → %s", _backup_file)
        except Exception as _be:
            logger.warning("[Agent Service] Backup failed: %s", _be)

        # ── Upsert into MongoDB agent_service collection ─────────────────────
        try:
            from pymongo import MongoClient
            from datetime import datetime, timezone
            _client = MongoClient(MONGO_URI, serverSelectionTimeoutMS=3000)
            _col = _client[MONGO_DB]["agent_service"]
            _payload = {
                **contract,
                "name": form_name,
                "updated_at": datetime.now(tz=timezone.utc).isoformat(),
            }
            _result = _col.update_one(
                {"name": form_name},
                {"$set": _payload},
                upsert=True,
            )
            _client.close()
            _action = "INSERTED" if _result.upserted_id else "UPDATED"
            logger.info("[Agent Service] MongoDB agent_service %s ← %s", _action, form_name)
        except Exception as _me:
            logger.warning("[Agent Service] MongoDB upsert failed for %s: %s", form_name, _me)

        return contract_path


