def _load_form_name_map() -> dict[str, dict]:
    """
    Load listFormJpToEn.json + listReportJpToEn.json and return dict keyed by access_form_name.
    Reports override forms if same name exists (shouldn't happen).
    """
    result: dict[str, dict] = {}
    for path in [_FORM_JP_TO_EN_PATH, _REPORT_JP_TO_EN_PATH]:
        if not path.exists():
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            for item in data.get("items", []):
                name = item.get("access_form_name", "")
                if name:
                    result[name] = item
        except Exception as exc:
            logger.warning("[agent_service] Failed to load %s: %s", path.name, exc)
    return result


def _resolve_feature_name(form_name: str, name_map: dict[str, dict]) -> str:
    """
    Derive the WPF feature name from the JP→EN map.

    Priority:
      1. wpf_viewmodel_name strip 'ViewModel'  → cleanest: "R005WorkRequest"
      2. wpf_view_name strip 'View'            → "R005WorkRequest"
      3. Fallback: strip leading F_ then remove non-word characters.
    """
    entry = name_map.get(form_name)
    if entry:
        # Prefer ViewModel name (no suffix = feature)
        vm = entry.get("wpf_viewmodel_name", "")
        if vm and vm.endswith("ViewModel"):
            feature = vm[:-9]   # "R005WorkRequestViewModel" → "R005WorkRequest"
            if feature:
                logger.debug("[agent_service] Feature from VM name: %r → %r", form_name, feature)
                return feature
        view_name = entry.get("wpf_view_name", "")
        if view_name and view_name.endswith("View"):
            feature = view_name[:-4]
            if feature:
                logger.debug("[agent_service] Feature from View name: %r → %r", form_name, feature)
                return feature

    # Fallback: strip leading F_ prefix then remove non-word characters
    name = form_name
    if name.startswith("F_"):
        name = name[2:]
    name = re.sub(r"[^\w]", "", name)
    logger.debug("[agent_service] Feature fallback: %r → %r", form_name, name)
    return name or "Default"

