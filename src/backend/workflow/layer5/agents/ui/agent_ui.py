    @staticmethod
    def _parse_jsonl_response(
        jsonl_raw: str,
        window_name: str,
        form_config: dict,
    ) -> dict:
        """
        Parse LLM JSONL output → structured ui_spec dict.

        Returns:
        {
          "window": { class, title, width, height, background, ... },
          "controls": [ {type, name, margin_left, margin_top, ...}, ... ]
        }

        Falls back to form_config values when LLM omits window fields.
        """
        lines   = [ln.strip() for ln in jsonl_raw.splitlines() if ln.strip()]
        window  : dict = {}
        controls: list = []

        for line in lines:
            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                logger.warning("[Agent UI] JSONL parse error on line: %s", line[:80])
                continue

            t = obj.get("type", "")
            if t == "window":
                window = obj
            elif t == "Section":
                # Start a new section container
                obj["controls"] = []
                controls.append(obj)
            elif t:
                # If we have a section, add to it, otherwise add to root
                if controls and controls[-1].get("type") == "Section":
                    controls[-1]["controls"].append(obj)
                else:
                    controls.append(obj)

        # ── [NEW] Post-process controls: Fix common LLM errors ──────────────
        def cleanup_control(ctrl: dict) -> dict:
            """Fix common LLM generation errors in control objects."""
            # 1. Fix VBA expressions in binding (e.g., "[Field1] & \" \" & [Field2]")
            binding = ctrl.get("binding", "")
            if binding and ("&" in binding or "[" in binding or "]" in binding):
                # Extract field names and create a computed property name
                # Example: "[請求先] & \" \" & [敬称名]" -> "請求先敬称"
                import re
                fields = re.findall(r'\[([^\]]+)\]', binding)
                if fields:
                    # Combine field names into a single property name
                    ctrl["binding"] = "".join(fields)
                    logger.warning(
                        "[Agent UI] Fixed VBA expression in binding: %s -> %s",
                        binding, ctrl["binding"]
                    )
            
            # 2. If LLM didn't create binding but control has control_source expression
            # Auto-generate binding from control_source
            if not binding:
                control_source = ctrl.get("data", {}).get("control_source", "")
                if control_source:
                    # Check if it's an expression (starts with =)
                    if control_source.startswith("="):
                        # Extract field names from expression
                        # Example: ="TEL:" & [電話番号] -> 電話番号TEL
                        import re
                        fields = re.findall(r'\[([^\]]+)\]', control_source)
                        if fields:
                            # Create computed property name
                            # Add suffix to indicate it's computed
                            ctrl["binding"] = "".join(fields) + "表示"
                            logger.info(
                                "[Agent UI] Auto-generated binding from expression: %s -> %s",
                                control_source, ctrl["binding"]
                            )
                    else:
                        # Simple field reference
                        ctrl["binding"] = control_source
                        logger.info(
                            "[Agent UI] Auto-generated binding from control_source: %s",
                            control_source
                        )
            
            # 2b. Normalize binding: ensure it matches ViewModel property name (PascalCase of physical_name)
            # LLM sometimes uses Access table field name (e.g. "ID") instead of PascalCase physical_name ("TxtID")
            binding = ctrl.get("binding", "")
            if binding and ctrl.get("type") in ("TextBox",):
                ctrl_name = ctrl.get("name", "")
                if ctrl_name:
                    expected = ctrl_name[0].upper() + ctrl_name[1:]  # PascalCase of control name
                    # Only normalize when:
                    # 1. ASCII binding (not a JP property name)
                    # 2. binding != expected
                    # 3. Binding looks like a raw field alias — it matches a SUFFIX of expected
                    #    e.g. expected="TxtID", binding="ID" → "ID" is suffix of "TxtID" ✅
                    #    e.g. expected="TxtPass", binding="Comment1" → "Comment1" not suffix of "TxtPass" ❌
                    is_ascii_binding = all(ord(c) < 128 for c in binding)
                    is_suffix = expected.upper().endswith(binding.upper()) and binding != expected
                    if is_ascii_binding and is_suffix:
                        ctrl["binding"] = expected
                        logger.info(
                            "[Agent UI] 🔧 Normalized binding: '%s' → '%s' (control: %s)",
                            binding, expected, ctrl_name,
                        )

            # 3. Ensure Image controls don't have nested structure
            # (This is handled in XAML assembly, but we can validate here)
            if ctrl.get("type") == "Image" and "picture" in ctrl:
                # Ensure picture has file extension
                pic = ctrl["picture"]
                if pic and "." not in pic:
                    ctrl["picture"] = f"{pic}.bmp"
            
            return ctrl
        
        # Apply cleanup to all controls
        cleaned_controls = []
        for ctrl in controls:
            if ctrl.get("type") == "Section":
                # Clean section's children
                ctrl["controls"] = [cleanup_control(c) for c in ctrl.get("controls", [])]
                cleaned_controls.append(ctrl)
            else:
                cleaned_controls.append(cleanup_control(ctrl))
        
        controls = cleaned_controls
        
        # ── Post-process controls: TextBlock doesn't support Border ──────
        # If LLM output a TextBlock but it has a border, convert it to Label.
        for ctrl in (controls if not any(c.get("type") == "Section" for c in controls) else [c for s in controls if s.get("type") == "Section" for c in s.get("controls", [])]):
             if ctrl.get("type") == "TextBlock":
                 if ctrl.get("border_brush") or ctrl.get("border_color") or ctrl.get("format", {}).get("border_color"):
                     ctrl["type"] = "Label"

        # ── Ensure window has all required attrs (fallback to form_config) ──
        correct_class = f"vba_brain.UI.WPF.Views.{sanitize_class_name(window_name)}"
        window.setdefault("class",            correct_class)
        window.setdefault("title",            form_config.get("caption", window_name))
        window.setdefault("width",            form_config.get("width",   600))
        
        # Use form height from form_config (calculated from form.bottom)
        # NOT from section heights (which can be larger than visible area)
        window.setdefault("height",           form_config.get("height", 400))
        window.setdefault("background",       form_config.get("background", "#FFFFFF"))
        window.setdefault("window_style",     "None" if form_config.get("allows_transparency") else "SingleBorderWindow")
        window.setdefault("resize_mode",      "NoResize" if not form_config.get("maxbutton") else "CanResize")
        window.setdefault("show_in_taskbar",  form_config.get("show_in_taskbar", False))
        window.setdefault("topmost",          form_config.get("topmost", True))
        window.setdefault("allows_transparency", form_config.get("allows_transparency", True))
        window.setdefault("startup_location", "CenterScreen")
        # Always enforce correct class — LLM may get it wrong
        window["class"] = correct_class

        logger.info(
            "[Agent UI] Parsed JSONL: window=%s, controls=%d",
            window_name, len(controls),
        )
        return {"window": window, "controls": controls}

    @staticmethod
    def _jsonl_to_xaml(ui_spec: dict, window_name: str) -> str:
        """
        Assemble final WPF XAML from ui_spec dict (deterministic — no LLM).

        Fixed by agent (NOT by LLM):
          - xmlns declarations (always correct)
          - x:Class format
          - PasswordChanged event wiring
          - Grid layout with HorizontalAlignment/VerticalAlignment/Margin
        """
        win = ui_spec.get("window", {})
        controls = ui_spec.get("controls", [])

        # ── Window attributes ───────────────────────────────────────────
        # xmlns are HARDCODED here — LLM never touches these
        w_class   = win.get("class", f"vba_brain.UI.WPF.Views.{sanitize_class_name(window_name)}")
        import html
        w_title   = html.escape(win.get("title") or form_config.get("caption") or window_name)
        w_width   = win.get("width", 600) + 16  # Compensation for Win10 borders
        w_height  = win.get("height", 400) + 39 # Compensation for title bar
        w_bg      = win.get("background") or win.get("format", {}).get("background", "#FFFFFF")
        w_style   = win.get("window_style", "SingleBorderWindow")
        w_resize  = win.get("resize_mode", "CanResize")
        w_taskbar = str(win.get("show_in_taskbar", True)).lower()
        w_topmost = str(win.get("topmost", False)).lower()
        w_transp  = "false"  # Default to false for stability (VBA migration)
        w_startup = win.get("startup_location", "CenterScreen")

        # AllowsTransparency requires WindowStyle=None
        if w_transp == "true" and w_style != "None":
            w_style = "None"

        lines: list[str] = [
            f'<Window x:Class="{w_class}"',
            f'        xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
            f'        xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
            f'        xmlns:i="http://schemas.microsoft.com/xaml/behaviors"',
            f'        xmlns:vm="clr-namespace:vba_brain.UI.WPF.ViewModels"',
            f'        Title="{w_title}"',
            f'        Width="{w_width}"',
            f'        Height="{w_height}"',
            f'        Background="{w_bg}"',
            f'        WindowStyle="{w_style}"',
            f'        ResizeMode="{w_resize}"',
            f'        ShowInTaskbar="{w_taskbar.capitalize()}"',
            f'        Topmost="{w_topmost.capitalize()}"',
            f'        AllowsTransparency="{w_transp.capitalize()}"',
            f'        WindowStartupLocation="{w_startup}">',
            f'    <Grid>',
        ]

        # ── Controls ────────────────────────────────────────────────────
        BOOL_ATTRS: dict[str, str] = {
            "is_readonly": "IsReadOnly",
        }

        for ctrl in controls:
            ctype  = ctrl.get("type", "TextBlock")
            name   = ctrl.get("name", "")
            ml     = ctrl.get("margin_left", 0)
            mt     = ctrl.get("margin_top", 0)
            width  = ctrl.get("width")
            height = ctrl.get("height")
            picture = ctrl.get("picture", "")

            comment = ctrl.get("comment", "")

            # Optional comment before element
            if comment:
                lines.append(f'        <!-- {comment} -->')

            # Opening tag
            tag_attrs: list[str] = []
            if name:
                tag_attrs.append(f'x:Name="{name}"')
            tag_attrs.append('HorizontalAlignment="Left"')
            tag_attrs.append('VerticalAlignment="Top"')
            tag_attrs.append(f'Margin="{ml},{mt},0,0"')
            if width  is not None: tag_attrs.append(f'Width="{width}"')
            if height is not None: tag_attrs.append(f'Height="{height}"')

            # Content / binding / command
            content = ctrl.get("content")
            binding = ctrl.get("binding")
            command = ctrl.get("command")

            if ctype in ("TextBox",) and binding:
                tag_attrs.append(f'Text="{{Binding {binding}}}"')
            
            inner_content = ""
            if ctype == "Image" and picture:
                # Image control: add Source directly as attribute, not as inner content
                img_path = f"/Resources/img/{window_name}/{picture}"
                tag_attrs.append(f'Source="{img_path}"')
                tag_attrs.append('Stretch="Uniform"')
                tag_attrs.append('RenderOptions.BitmapScalingMode="HighQuality"')
            elif picture:
                # Button/Label with picture: use inner StackPanel
                img_path = f"/Resources/img/{window_name}/{picture}"
                if content:
                    inner_content = f'<StackPanel Orientation="Horizontal"><Image Source="{img_path}" Stretch="Uniform" RenderOptions.BitmapScalingMode="HighQuality" /><TextBlock Text="{content}" VerticalAlignment="Center" Margin="5,0,0,0"/></StackPanel>'
                else:
                    inner_content = f'<Image Source="{img_path}" Stretch="Uniform" RenderOptions.BitmapScalingMode="HighQuality" />'
            elif ctype in ("Label", "Button") and content is not None:
                tag_attrs.append(f'Content="{content}"')

            if command and ctype in ("Button", "RadioButton", "CheckBox", "ToggleButton", "MenuItem", "Hyperlink"):
                tag_attrs.append(f'Command="{{Binding {command}}}"')

            # Font
            ff = ctrl.get("font_family")
            fs = ctrl.get("font_size")
            fw = ctrl.get("font_weight")
            if ff: tag_attrs.append(f'FontFamily="{ff}"')
            if fs: tag_attrs.append(f'FontSize="{fs}"')
            if fw: tag_attrs.append(f'FontWeight="{fw}"')

            # Colors
            fg = ctrl.get("foreground")
            bg = ctrl.get("background")
            bb = ctrl.get("border_brush")
            if fg: tag_attrs.append(f'Foreground="{fg}"')
            if bg and bg != "Transparent": tag_attrs.append(f'Background="{bg}"')
            if bb: tag_attrs.append(f'BorderBrush="{bb}"')

            # Bool attributes
            for key, xaml_attr in BOOL_ATTRS.items():
                if ctrl.get(key):
                    tag_attrs.append(f'{xaml_attr}="True"')

            # Visibility
            if ctrl.get("visible") is False:
                tag_attrs.append('Visibility="Collapsed"')

            # Alignment (Label)
            ha = ctrl.get("horizontal_content_alignment")
            va = ctrl.get("vertical_content_alignment")
            if ha: tag_attrs.append(f'HorizontalContentAlignment="{ha}"')
            if va: tag_attrs.append(f'VerticalContentAlignment="{va}"')

            # Render element (indent attrs for readability)
            first = tag_attrs[0]
            rest  = tag_attrs[1:]
            indent = " " * (8 + len(ctype) + 2)   # align after <Type_name_
            body  = f'\n{indent}'.join([first] + rest)
            
            if inner_content:
                lines.append(f'        <{ctype} {body}>')
                lines.append(f'            {inner_content}')
                lines.append(f'        </{ctype}>')
            else:
                lines.append(f'        <{ctype} {body} />')

        lines.append('    </Grid>')
        lines.append('</Window>')
        return "\n".join(lines)

