    @staticmethod
    def _parse_jsonl_response(
        jsonl_raw: str,
        window_name: str,
        form_config: dict,
    ) -> dict:
        """
        Parse LLM JSONL output → structured ui_spec dict.

        Returns:
        {
          "window": { class, title, width, height, background, ... },
          "controls": [ {type, name, margin_left, margin_top, ...}, ... ]
        }

        Falls back to form_config values when LLM omits window fields.
        """
        lines   = [ln.strip() for ln in jsonl_raw.splitlines() if ln.strip()]
        window  : dict = {}
        controls: list = []

        for line in lines:
            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                logger.warning("[Agent UI] JSONL parse error on line: %s", line[:80])
                continue
            if not isinstance(obj, dict):
                continue

            t = obj.get("type", "")
            if t == "window":
                window = obj
            elif t == "Section":
                # Start a new section container
                obj["controls"] = []
                controls.append(obj)
            elif t:
                # If we have a section, add to it, otherwise add to root
                if controls and controls[-1].get("type") == "Section":
                    controls[-1]["controls"].append(obj)
                else:
                    controls.append(obj)

        # ── [NEW] Post-process controls: Fix common LLM errors ──────────────
        def cleanup_control(ctrl: dict) -> dict:
            """Fix common LLM generation errors in control objects."""
            # 1. Fix VBA expressions in binding (e.g., "[Field1] & \" \" & [Field2]")
            binding = ctrl.get("binding", "")
            if binding and ("&" in binding or "[" in binding or "]" in binding):
                # Extract field names and create a computed property name
                # Example: "[請求先] & \" \" & [敬称名]" -> "請求先敬称"
                import re
                fields = re.findall(r'\[([^\]]+)\]', binding)
                if fields:
                    # Combine field names into a single property name
                    ctrl["binding"] = "".join(fields)
                    logger.warning(
                        "[Agent UI] Fixed VBA expression in binding: %s -> %s",
                        binding, ctrl["binding"]
                    )
            
            # 2. If LLM didn't create binding but control has control_source expression
            # Auto-generate binding from control_source
            if not binding:
                control_source = ctrl.get("data", {}).get("control_source", "")
                if control_source:
                    # Check if it's an expression (starts with =)
                    if control_source.startswith("="):
                        # Extract field names from expression
                        # Example: ="TEL:" & [電話番号] -> 電話番号TEL
                        import re
                        fields = re.findall(r'\[([^\]]+)\]', control_source)
                        if fields:
                            # Create computed property name
                            # Add suffix to indicate it's computed
                            ctrl["binding"] = "".join(fields) + "表示"
                            logger.info(
                                "[Agent UI] Auto-generated binding from expression: %s -> %s",
                                control_source, ctrl["binding"]
                            )
                    else:
                        # Simple field reference
                        ctrl["binding"] = control_source
                        logger.info(
                            "[Agent UI] Auto-generated binding from control_source: %s",
                            control_source
                        )
            
            # 2b. Normalize binding: ensure it matches ViewModel property name (PascalCase of physical_name)
            # LLM sometimes uses Access table field name (e.g. "ID") instead of PascalCase physical_name ("TxtID")
            binding = ctrl.get("binding", "")
            if binding and ctrl.get("type") in ("TextBox",):
                ctrl_name = ctrl.get("name", "")
                if ctrl_name:
                    expected = ctrl_name[0].upper() + ctrl_name[1:]  # PascalCase of control name
                    # Only normalize when:
                    # 1. ASCII binding (not a JP property name)
                    # 2. binding != expected
                    # 3. Binding looks like a raw field alias — it matches a SUFFIX of expected
                    #    e.g. expected="TxtID", binding="ID" → "ID" is suffix of "TxtID" ✅
                    #    e.g. expected="TxtPass", binding="Comment1" → "Comment1" not suffix of "TxtPass" ❌
                    is_ascii_binding = all(ord(c) < 128 for c in binding)
                    is_suffix = expected.upper().endswith(binding.upper()) and binding != expected
                    if is_ascii_binding and is_suffix:
                        ctrl["binding"] = expected
                        logger.info(
                            "[Agent UI] 🔧 Normalized binding: '%s' → '%s' (control: %s)",
                            binding, expected, ctrl_name,
                        )

            # 3. Ensure Image controls don't have nested structure
            # (This is handled in XAML assembly, but we can validate here)
            if ctrl.get("type") == "Image" and "picture" in ctrl:
                # Ensure picture has file extension
                pic = ctrl["picture"]
                if pic and "." not in pic:
                    ctrl["picture"] = f"{pic}.bmp"
            
            return ctrl
        
        # Apply cleanup to all controls
        cleaned_controls = []
        for ctrl in controls:
            if ctrl.get("type") == "Section":
                # Clean section's children
                ctrl["controls"] = [cleanup_control(c) for c in ctrl.get("controls", [])]
                cleaned_controls.append(ctrl)
            else:
                cleaned_controls.append(cleanup_control(ctrl))
        
        controls = cleaned_controls
        
        # ── Post-process controls: TextBlock doesn't support Border ──────
        # If LLM output a TextBlock but it has a border, convert it to Label.
        for ctrl in (controls if not any(c.get("type") == "Section" for c in controls) else [c for s in controls if s.get("type") == "Section" for c in s.get("controls", [])]):
             if ctrl.get("type") == "TextBlock":
                 if ctrl.get("border_brush") or ctrl.get("border_color") or ctrl.get("format", {}).get("border_color"):
                     ctrl["type"] = "Label"

        # ── Ensure window has all required attrs (fallback to form_config) ──
        correct_class = f"vba_brain.UI.WPF.Views.{sanitize_class_name(window_name)}"
        window.setdefault("class",            correct_class)
        window.setdefault("title",            form_config.get("caption", window_name))
        window.setdefault("width",            form_config.get("width",   600))
        
        # Use form height from form_config (calculated from form.bottom)
        # NOT from section heights (which can be larger than visible area)
        window.setdefault("height",           form_config.get("height", 400))
        window.setdefault("background",       form_config.get("background", "#FFFFFF"))
        window.setdefault("window_style",     "None" if form_config.get("allows_transparency") else "SingleBorderWindow")
        window.setdefault("resize_mode",      "NoResize" if not form_config.get("maxbutton") else "CanResize")
        window.setdefault("show_in_taskbar",  form_config.get("show_in_taskbar", False))
        window.setdefault("topmost",          form_config.get("topmost", True))
        window.setdefault("allows_transparency", form_config.get("allows_transparency", True))
        window.setdefault("startup_location", "CenterScreen")
        # Always enforce correct class — LLM may get it wrong
        window["class"] = correct_class

        logger.info(
            "[Agent UI] Parsed JSONL: window=%s, controls=%d",
            window_name, len(controls),
        )
        return {"window": window, "controls": controls}

    @staticmethod
    def _to_avalonia_xaml(xaml: str, view_class: str, password_binding: str | None = None) -> str:
        """
        Post-process a WPF XAML string into an Avalonia .axaml string.

        Centralized converter — applied at the single output chokepoint so it
        covers whatever the skeleton-injection path produced. Deterministic.

        password_binding: ViewModel property for the converted PasswordBox's Text (Avalonia's
        TextBox+PasswordChar binds directly; WPF needed a PasswordChanged code-behind handler).
        """
        # 1. Root namespaces: WPF presentation NS → Avalonia NS
        xaml = xaml.replace(
            'xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
            'xmlns="https://github.com/avaloniaui"',
        )
        # 2. Drop the WPF behaviors namespace (Avalonia uses native events instead)
        xaml = re.sub(r'\s*xmlns:i="http://schemas\.microsoft\.com/xaml/behaviors"', '', xaml)

        # 3. Remove WPF-only <Window> attributes that Avalonia does not support
        for attr in ("WindowStyle", "ResizeMode", "AllowsTransparency", "SizeToContent"):
            xaml = re.sub(rf'\s*{attr}\s*=\s*"[^"]*"', '', xaml)

        # 4. x:Class points at the Avalonia view namespace
        xaml = re.sub(
            r'(x:Class\s*=\s*")[^"]*"',
            rf'\g<1>vba_brain.UI.Avalonia.Views.{view_class}"',
            xaml, count=1,
        )
        # vm clr-namespace → Avalonia using: form
        xaml = xaml.replace(
            'xmlns:vm="clr-namespace:vba_brain.UI.WPF.ViewModels"',
            'xmlns:vm="using:vba_brain.UI.Avalonia.ViewModels"',
        )
        xaml = xaml.replace('vba_brain.UI.WPF', 'vba_brain.UI.Avalonia')

        # 4b. Compiled bindings (AvaloniaUseCompiledBindingsByDefault=true) require an
        #     x:DataType on the root. Derive the ViewModel name from the view class
        #     (FLoginView → FLoginViewModel) and ensure the vm: namespace + x:DataType exist.
        vm_name = (view_class[:-4] + "ViewModel") if view_class.endswith("View") else (view_class + "ViewModel")
        if 'xmlns:vm=' not in xaml:
            xaml = re.sub(
                r'(xmlns:x="http://schemas\.microsoft\.com/winfx/2006/xaml")',
                r'\1\n        xmlns:vm="using:vba_brain.UI.Avalonia.ViewModels"',
                xaml, count=1,
            )
        if 'x:DataType=' not in xaml:
            xaml = re.sub(
                r'(<Window\b)',
                rf'\1 x:DataType="vm:{vm_name}"',
                xaml, count=1,
            )

        # 5. PasswordBox → TextBox with PasswordChar (Avalonia has no PasswordBox)
        def _password_box(m: re.Match) -> str:
            attrs = m.group(1)
            if password_binding and not re.search(r'\sText\s*=', attrs):
                attrs = f' Text="{{Binding {password_binding}}}"' + attrs
            return f'<TextBox PasswordChar="*"{attrs}'
        xaml = re.sub(r'<PasswordBox\b([^>]*?)(?=/?>)', _password_box, xaml)
        xaml = xaml.replace('</PasswordBox>', '</TextBox>')
        # Drop WPF-only PasswordChanged handler attribute
        xaml = re.sub(r'\s*PasswordChanged\s*=\s*"[^"]*"', '', xaml)

        # 6. Visibility="Collapsed/Hidden/Visible" → IsVisible bool
        xaml = re.sub(r'Visibility\s*=\s*"(Collapsed|Hidden)"', 'IsVisible="False"', xaml)
        xaml = re.sub(r'Visibility\s*=\s*"Visible"', 'IsVisible="True"', xaml)

        # 7. Remove RenderOptions.BitmapScalingMode (WPF attached prop, different in Avalonia)
        xaml = re.sub(r'\s*RenderOptions\.BitmapScalingMode\s*=\s*"[^"]*"', '', xaml)

        # 8. Remove WPF behaviors trigger blocks (Microsoft.Xaml.Behaviors has no Avalonia 12
        #    equivalent). Button Command bindings are preserved natively; non-button command
        #    triggers are wired in the code-behind instead (see _collect_control_events).
        xaml = re.sub(
            r'\s*<i:Interaction\.Triggers>[\s\S]*?</i:Interaction\.Triggers>',
            '', xaml,
        )

        # 9. Root element <Window> stays (Avalonia has Window).
        return xaml

