    @staticmethod
    def _jsonl_to_grid_content(
        controls: list[dict],
        form_name: str = "Window",
        event_handler_map: dict[str, str] | None = None,
        vba_mid_map: dict[str, str] | None = None,
    ) -> str:
        """
        Generate only the <Grid> children XAML.
        Supports recursive 'Section' grouping.

        Args:
            controls: list of control dicts from ui_spec.
            form_name: used to resolve image resource paths.
            event_handler_map: dict mapping control name → {vba_event: cs_method_name}
                Derived from vm_bindings.event_handlers for deterministic XAML event wiring.
        """
        lines: list[str] = []
        BOOL_ATTRS: dict[str, str] = {"is_readonly": "IsReadOnly"}

        # VBA event name → WPF routed event attribute name
        # Rules:
        #   - Button/ButtonBase: onclick → Click
        #   - Label/Control (non-button): ondblclick → MouseDoubleClick
        #     (Label is a ContentControl — inherits Mouse events from UIElement)
        #   - PasswordBox: afterupdate → PasswordChanged (special case handled separately)
        #   - TextBox: afterupdate → TextChanged
        VBA_TO_XAML_EVENT: dict[str, dict[str, str]] = {
            # format: {vba_event: {wpf_type: xaml_event_attr}}
            "onclick": {
                "Button":      "Click",
                "RadioButton": "Click",
                "CheckBox":    "Click",
                "__default__": "MouseLeftButtonUp",
            },
            "ondblclick": {
                "__default__": "MouseDoubleClick",
            },
            "dblclick": {
                "__default__": "MouseDoubleClick",
            },
            "afterupdate": {
                "PasswordBox": "PasswordChanged",
                "TextBox":     "TextChanged",
                "__default__": "LostFocus",
            },
            "beforeupdate": {
                "__default__": "PreviewLostFocus",
            },
            "onkeydown": {
                "__default__": "KeyDown",
            },
            "onkeyup": {
                "__default__": "KeyUp",
            },
            "ongotfocus": {
                "__default__": "GotFocus",
            },
            "onlostfocus": {
                "__default__": "LostFocus",
            },
        }

        def _resolve_xaml_event(vba_event: str, wpf_type: str) -> str | None:
            """Return the XAML event attribute name for a given VBA event + WPF control type."""
            mapping = VBA_TO_XAML_EVENT.get(vba_event.lower())
            if not mapping:
                return None
            return mapping.get(wpf_type) or mapping.get("__default__")

        for ctrl in controls:
            ctype   = ctrl.get("type", "TextBlock")
            
            # Handle Sections (Containers)
            if ctype == "Section":
                sec_name = ctrl.get("name", "Section")
                sec_w    = ctrl.get("width")
                sec_h    = ctrl.get("height")
                sec_bg   = ctrl.get("background", "Transparent")
                ml       = ctrl.get("margin_left", 0)
                mt       = ctrl.get("margin_top", 0)
                
                inner_xaml = UIAgent._jsonl_to_grid_content(
                    ctrl.get("controls", []), form_name, event_handler_map, vba_mid_map
                )
                
                lines.append(f'        <!-- Section: {sec_name} -->')
                lines.append(f'        <Grid x:Name="sec_{sanitize_xaml_name(sec_name)}" Width="{sec_w}" Height="{sec_h}" Background="{sec_bg}" Margin="{ml},{mt},0,0" HorizontalAlignment="Left" VerticalAlignment="Top">')
                # Indent inner XAML for readability
                for inner_ln in inner_xaml.splitlines():
                    if inner_ln.strip():
                        lines.append(f'    {inner_ln}')
                lines.append('        </Grid>')
                continue

            name    = ctrl.get("name", "")
            # Coordinate extraction with fallback
            ml = ctrl.get("margin_left")
            if ml is None: ml = ctrl.get("format", {}).get("left", 0)
            
            mt = ctrl.get("margin_top")
            if mt is None: mt = ctrl.get("format", {}).get("top", 0)
            
            width  = ctrl.get("width")
            if width is None: width = ctrl.get("format", {}).get("width")
            
            height = ctrl.get("height")
            if height is None: height = ctrl.get("format", {}).get("height")

            comment = ctrl.get("comment", "")
            if comment:
                import html
                lines.append(f'        <!-- {html.escape(comment)} -->')

            content = ctrl.get("content") or ctrl.get("format", {}).get("caption", "")
            if isinstance(content, str):
                import html
                content = html.escape(unicodedata.normalize('NFKC', content))
            
            binding = ctrl.get("binding")
            command = ctrl.get("command")
            picture = ctrl.get("picture") or ctrl.get("format", {}).get("picture", "")

            # ── Deterministic command injection từ event_handler_map ──────────
            # LLM có thể gen sai hoặc bỏ sót command field.
            # Nếu control có trong event_handler_map → override bằng F-ID Command
            # đúng dựa vào vba_mid_map (không phụ thuộc LLM).
            # Button: 1 command (onclick) — dùng command attribute
            # Label/non-Button: có thể nhiều events — sẽ được gen thành Behaviors triggers bên dưới
            if event_handler_map and name and name in event_handler_map:
                _ctrl_evts = event_handler_map[name]
                # Lấy F-ID command name từ event đầu tiên (onclick ưu tiên)
                _primary_vba = next(
                    (v for v in ("onclick", "ondblclick", "dblclick") if v in _ctrl_evts),
                    next(iter(_ctrl_evts), None)
                )
                if _primary_vba:
                    _cs_method = _ctrl_evts[_primary_vba]
                    # Resolve module_id từ cs_method (e.g. "F005_DblClick" → "F005")
                    _mid = _cs_method.split("_")[0] if "_" in _cs_method else ""
                    if _mid and re.match(r'^F\d{3}$', _mid):
                        command = f"{_mid}Command"

            # Always use absolute positioning to match Access WYSIWYG
            tag_attrs: list[str] = []
            if name:
                tag_attrs.append(f'x:Name="{sanitize_xaml_name(name)}"')
            
            tag_attrs.append('HorizontalAlignment="Left"')
            tag_attrs.append(f'Margin="{ml},{mt},0,0"')

            # Apply text alignment internally (use HorizontalContentAlignment for controls that don't support TextAlignment like PasswordBox/Label)
            text_align = ctrl.get("text_align") or ctrl.get("format", {}).get("text_align", "Left")
            if text_align in ("Center", "Right"):
                if ctype == "TextBox":
                    tag_attrs.append(f'TextAlignment="{text_align}"')
                else:
                    tag_attrs.append(f'HorizontalContentAlignment="{text_align}"')

            tag_attrs.append('VerticalAlignment="Top"')
            
            if width  is not None: tag_attrs.append(f'Width="{width}"')
            if height is not None: tag_attrs.append(f'Height="{height}"')

            if ctype == "TextBox" and binding:
                tag_attrs.append(f'Text="{{Binding {binding}}}"')
            
            inner_content = ""
            if picture:
                img_path = f"/Resources/img/{form_name}/{picture}"
                # If button is wide enough, show both icon and text. Otherwise, icon only.
                if content and (width is None or width > 60):
                    inner_content = (
                        f'<StackPanel Orientation="Horizontal">'
                        f'<Image Source="{img_path}" Stretch="Uniform" Width="16" Height="16" RenderOptions.BitmapScalingMode="HighQuality" />'
                        f'<TextBlock Text="{content}" VerticalAlignment="Center" Margin="5,0,0,0"/>'
                        f'</StackPanel>'
                    )
                else:
                    # Icon-only button: do NOT set Width/Height on Image — let Stretch="Uniform"
                    # fill the Button's content area naturally. Setting explicit dimensions equal
                    # to the button size causes clipping due to WPF button chrome/border.
                    inner_content = (
                        f'<Image Source="{img_path}" Stretch="Uniform"'
                        f' RenderOptions.BitmapScalingMode="HighQuality" />'
                    )
            elif ctype in ("Label", "Button") and content is not None:
                tag_attrs.append(f'Content="{content}"')
            
            # Default Padding="0" to match Access layout (prevents vertical offset and clipping)
            if ctype in ("Label", "Button", "TextBox", "PasswordBox", "ComboBox"):
                # Only add default Padding/Alignment if not explicitly provided later
                if ctrl.get("padding") is None:
                    tag_attrs.append('Padding="0"')
                if ctype in ("TextBox", "PasswordBox") and ctrl.get("vertical_content_alignment") is None:
                    tag_attrs.append('VerticalContentAlignment="Center"')

            if ctype == "PasswordBox" and ctrl.get("password_event"):
                tag_attrs.append('PasswordChanged="PasswordBox_PasswordChanged"')

            # ── Deterministic event wiring from vm_bindings.event_handlers ──────
            # Priority: event_handler_map (from vm_bindings) > ctrl["events"] (from LLM JSON)
            # This ensures XAML events are always consistent with code-behind stubs.
            ctrl_events_wired: set[str] = set()  # track which vba events we've wired

            if event_handler_map and name:
                ctrl_eh = event_handler_map.get(name, {})
                for vba_evt, cs_method in ctrl_eh.items():
                    # Skip macro handlers (no code-behind stub)
                    if cs_method.lower().startswith("macro."):
                        continue
                    # Skip afterupdate for PasswordBox — handled by password_event flag above
                    if vba_evt == "afterupdate" and ctype == "PasswordBox" and ctrl.get("password_event"):
                        ctrl_events_wired.add(vba_evt)
                        continue
                    # Button with Command binding → prefer Command over Click event handler (MVVM)
                    if vba_evt in ("onclick", "click") and ctype == "Button" and command:
                        ctrl_events_wired.add(vba_evt)
                        continue
                    # Non-Button controls with command → sẽ dùng InvokeCommandAction (Behaviors)
                    # KHÔNG wire event handler attrs — tránh duplicate wiring gây lỗi XAML
                    if ctype not in ("Button", "RadioButton", "CheckBox", "ToggleButton", "MenuItem") and command:
                        ctrl_events_wired.add(vba_evt)
                        continue
                    xaml_evt = _resolve_xaml_event(vba_evt, ctype)
                    if xaml_evt:
                        tag_attrs.append(f'{xaml_evt}="{cs_method}"')
                        ctrl_events_wired.add(vba_evt)
                        ctrl_events_wired.add(vba_evt)

            # Fallback: wire events from ctrl["events"] dict if not already wired
            # (for controls whose events were not captured in vm_bindings)
            for vba_evt, handler_val in (ctrl.get("events") or {}).items():
                if vba_evt in ctrl_events_wired:
                    continue
                if not handler_val or handler_val.lower().startswith("macro."):
                    continue
                if vba_evt == "afterupdate" and ctype == "PasswordBox" and ctrl.get("password_event"):
                    continue
                # Non-Button controls with command → dùng Behaviors, không wire attr
                if ctype not in ("Button", "RadioButton", "CheckBox", "ToggleButton", "MenuItem") and command:
                    ctrl_events_wired.add(vba_evt)
                    continue
                xaml_evt = _resolve_xaml_event(vba_evt, ctype)
                if xaml_evt:
                    # Resolve tên handler sang F-ID nếu có vba_mid_map
                    if vba_mid_map:
                        from agents.ui.tool_skeleton import get_cs_handler_name
                        mid = vba_mid_map.get(handler_val, "")
                        resolved = get_cs_handler_name(mid, vba_evt) if mid else handler_val
                    else:
                        resolved = handler_val
                    tag_attrs.append(f'{xaml_evt}="{resolved}"')

            # ── Command binding ─────────────────────────────────────────────
            # Button/ButtonBase: Command attribute trực tiếp
            # Label/non-Button: dùng InvokeCommandAction (Behaviors) — không cần code-behind
            # Một control có thể có nhiều events (onclick + ondblclick) → nhiều EventTriggers
            if command:
                if ctype in ("Button", "RadioButton", "CheckBox", "ToggleButton", "MenuItem", "Hyperlink"):
                    tag_attrs.append(f'Command="{{Binding {command}}}"')
                else:
                    # Map vba_event → (xaml_event, command_name)
                    # Thu thập tất cả events của control này có command mapping
                    # ctrl["events"] = {"onclick": "F006_Click", "ondblclick": "F007_DblClick"} (LLM-provided names)
                    # vm_bindings đã remap sang F-ID Command names qua fid_cmd_map
                    _VBA_TO_XAML = {
                        "onclick":     "MouseLeftButtonUp",
                        "ondblclick":  "MouseDoubleClick",
                        "dblclick":    "MouseDoubleClick",
                        "afterupdate": "LostFocus",      # Access AfterUpdate fires when leaving the control
                        "onlostfocus": "LostFocus",
                        "ongotfocus":  "GotFocus",
                    }
                    # Build list of (xaml_event, fid_command) for this control
                    _beh_triggers: list[tuple[str, str]] = []
                    _seen_xaml_evts: set[str] = set()

                    # Primary: dùng event_handler_map để lấy F-ID → Command mapping
                    if event_handler_map and name:
                        ctrl_eh = event_handler_map.get(name, {})
                        for _vba_evt, _cs_method in ctrl_eh.items():
                            _xaml_evt = _VBA_TO_XAML.get(_vba_evt.lower())
                            if not _xaml_evt or _xaml_evt in _seen_xaml_evts:
                                continue
                            # Resolve F-ID command per event (F006_Click → F006Command, F007_DblClick → F007Command)
                            _mid = _cs_method.split("_")[0] if "_" in _cs_method else ""
                            _fid_cmd = f"{_mid}Command" if (_mid and re.match(r'^F\d{3}$', _mid)) else command
                            _beh_triggers.append((_xaml_evt, _fid_cmd))
                            _seen_xaml_evts.add(_xaml_evt)

                    # Fallback: nếu không có event_handler_map, dùng ctrl["events"]
                    if not _beh_triggers:
                        for _vba_evt in (ctrl.get("events") or {}):
                            _xaml_evt = _VBA_TO_XAML.get(_vba_evt.lower())
                            if _xaml_evt and _xaml_evt not in _seen_xaml_evts:
                                _beh_triggers.append((_xaml_evt, command))
                                _seen_xaml_evts.add(_xaml_evt)

                    if not _beh_triggers:
                        # Fallback cuối: dùng command với MouseLeftButtonUp
                        _beh_triggers = [("MouseLeftButtonUp", command)]

                    # Xóa event handler attrs đã wire (tránh conflict với Behaviors)
                    _evts_to_remove = {evt for evt, _ in _beh_triggers}
                    tag_attrs = [a for a in tag_attrs
                                 if not any(a.startswith(f'{e}=') for e in _evts_to_remove)]

                    # Lưu list triggers để gen Interaction.Triggers block
                    ctrl["_behaviors_triggers"] = _beh_triggers

            ff = ctrl.get("font_family") or ctrl.get("format", {}).get("font_family")
            fs = ctrl.get("font_size")   or ctrl.get("format", {}).get("font_size")
            fw = ctrl.get("font_weight") or ctrl.get("format", {}).get("font_weight")
            if ff: tag_attrs.append(f'FontFamily="{ff}"')
            if fs:
                # Scale font size: Access Points -> WPF Pixels (approx 1.33 ratio)
                try:
                    scaled_fs = round(float(fs) * 1.33)
                    tag_attrs.append(f'FontSize="{scaled_fs}"')
                except:
                    tag_attrs.append(f'FontSize="{fs}"')
            if fw: tag_attrs.append(f'FontWeight="{fw}"')

            fg = ctrl.get("foreground") or ctrl.get("format", {}).get("foreground")
            bg = ctrl.get("background") or ctrl.get("format", {}).get("background")
            bb = ctrl.get("border_brush") or ctrl.get("format", {}).get("border_brush") or ctrl.get("format", {}).get("border_color")
            
            # BorderBrush and Background are mainly for Control-derived types. 
            # TextBlock and Shape types handle these differently.
            if fg: tag_attrs.append(f'Foreground="{fg}"')
            
            is_control = ctype in ("Label", "Button", "TextBox", "PasswordBox", "ComboBox", "CheckBox", "RadioButton", "ListBox", "Border")
            
            if bg and bg != "Transparent":
                # Always allow background for controls and layout containers
                if is_control or ctype in ("TextBlock", "Grid", "Border", "Section"):
                    tag_attrs.append(f'Background="{bg}"')
            
            if bb and is_control:
                tag_attrs.append(f'BorderBrush="{bb}"')
                tag_attrs.append('BorderThickness="1"')

            for key, xaml_attr in BOOL_ATTRS.items():
                if ctrl.get(key):
                    tag_attrs.append(f'{xaml_attr}="True"')

            if ctrl.get("visible") is False:
                tag_attrs.append('Visibility="Collapsed"')

            padding = ctrl.get("padding")
            if padding is not None:
                tag_attrs.append(f'Padding="{padding}"')

            hca = ctrl.get("h_content_align") or ctrl.get("horizontal_content_alignment")
            if hca:
                tag_attrs.append(f'HorizontalContentAlignment="{hca}"')
            
            ta = ctrl.get("text_alignment")
            if ta:
                tag_attrs.append(f'TextAlignment="{ta}"')

            va = ctrl.get("vertical_content_alignment")
            if va:
                tag_attrs.append(f'VerticalContentAlignment="{va}"')

            first  = tag_attrs[0] if tag_attrs else ""
            rest   = tag_attrs[1:]
            indent = " " * (8 + len(ctype) + 2)
            body   = f'\n{indent}'.join([first] + rest)

            beh_triggers: list[tuple[str, str]] = ctrl.get("_behaviors_triggers", [])

            if inner_content or beh_triggers:
                lines.append(f'        <{ctype} {body}>')
                if inner_content:
                    lines.append(f'            {inner_content}')
                if beh_triggers:
                    # InvokeCommandAction — MVVM pattern cho non-Button controls
                    # Hỗ trợ nhiều events trên cùng một control (onclick + ondblclick)
                    lines.append('            <i:Interaction.Triggers>')
                    for _xaml_evt, _fid_cmd in beh_triggers:
                        lines.append(f'                <i:EventTrigger EventName="{_xaml_evt}">')
                        lines.append(f'                    <i:InvokeCommandAction Command="{{Binding {_fid_cmd}}}" />')
                        lines.append('                </i:EventTrigger>')
                    lines.append('            </i:Interaction.Triggers>')
                lines.append(f'        </{ctype}>')
            else:
                lines.append(f'        <{ctype} {body} />')

        return "\n".join(lines)


    @staticmethod
    def _bound_property_names(controls: list) -> list[str]:
        """Plain `binding` names referenced by the controls (nested included), in document order."""
        names: list[str] = []
        for ctrl in controls or []:
            binding = str(ctrl.get("binding") or "").strip()
            if re.fullmatch(r"[A-Za-z_]\w*", binding) and binding not in names:
                names.append(binding)
            for nested in UIAgent._bound_property_names(ctrl.get("controls", [])):
                if nested not in names:
                    names.append(nested)
        return names

    @staticmethod
    def _sync_bound_properties(vm_bindings: dict, controls: list) -> None:
        """
        Make every property the AXAML binds exist on the ViewModel skeleton, spelled exactly the
        same — compiled bindings are case-sensitive and a miss is a build error (AVLN2000).
        Unbound Access text boxes that VBA fills (txtID) are never inferred from the controls,
        and inferred names keep the control's casing (txtProductID) while the AXAML binds
        PascalCase (TxtProductID). The PasswordBox property is left alone (tool_skeleton renames
        it to TxtPass, which is what the converted PasswordBox binds).
        """
        props = vm_bindings.setdefault("properties", [])
        for name in UIAgent._bound_property_names(controls):
            same = next((i for i, p in enumerate(props) if p.lower() == name.lower()), None)
            if same is None:
                props.append(name)
            elif props[same] != vm_bindings.get("password_property"):
                props[same] = name

    @staticmethod
    def _collect_control_events(
        controls: list[dict], fid_map: dict[str, str] | None,
    ) -> list[tuple[str, str, str]]:
        """
        (x:Name, Avalonia event, F###Command) for the non-Button command triggers that
        _jsonl_to_grid_content recorded. Avalonia has no Interaction.Triggers, so the code-behind
        subscribes the control event instead. Only commands the ViewModel defines are wired.
        """
        known_cmds = {f"{fid}Command" for fid in (fid_map or {}).values()}
        wiring: list[tuple[str, str, str]] = []
        seen: set[tuple[str, str]] = set()

        def walk(ctrls: list[dict]) -> None:
            for ctrl in ctrls:
                if ctrl.get("controls"):
                    walk(ctrl["controls"])
                name = ctrl.get("name", "")
                if not name:
                    continue
                field = sanitize_xaml_name(name)
                for xaml_evt, cmd in ctrl.get("_behaviors_triggers", []) or []:
                    event = _AVALONIA_CONTROL_EVENTS.get(xaml_evt)
                    if event and cmd in known_cmds and (field, event) not in seen:
                        seen.add((field, event))
                        wiring.append((field, event, cmd))

        walk(controls or [])
        return wiring

    @staticmethod
    def _inject_into_skeleton(
        source_file: Path,
        ui_spec: dict,
        form_name: str,
        grid_content: str,
    ) -> str:
        """
        Read existing skeleton .xaml, update Window-level attributes from
        ui_spec, and inject Grid children — preserving all xmlns declarations.

        Strategy:
          1. Keep xmlns:*, mc:Ignorable from existing file (x:Class is overwritten by caller)
          2. Update Title, Width, Height, Background, WindowStyle, ResizeMode,
             ShowInTaskbar, Topmost, AllowsTransparency, WindowStartupLocation
          3. Replace <Grid> inner content with generated controls
        """
        win = ui_spec.get("window", {})

        # Read existing skeleton (fallback: build from scratch if file missing)
        if source_file.exists():
            original = source_file.read_text(encoding="utf-8")
        else:
            logger.warning("[Agent UI] Skeleton %s not found — generating from scratch", source_file.name)
            # Minimal fallback skeleton
            original = (
                f'<Window x:Class="vba_brain.UI.WPF.Views.{sanitize_class_name(form_name)}"\n'
                f'        xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"\n'
                f'        xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"\n'
                f'        xmlns:i="http://schemas.microsoft.com/xaml/behaviors"\n'
                f'        Title="{form_name}" Height="450" Width="800">\n'
                f'    <Grid>\n    </Grid>\n</Window>\n'
            )

        # ── Ensure xmlns:i (Microsoft.Xaml.Behaviors) is declared ─────────
        # Required for i:Interaction.Triggers / i:InvokeCommandAction
        _behaviors_ns = 'xmlns:i="http://schemas.microsoft.com/xaml/behaviors"'
        if _behaviors_ns not in original:
            original = original.replace(
                'xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
                'xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"\n'
                f'        {_behaviors_ns}',
                1,
            )

        # ── Update Window-level attributes ─────────────────────────────────
        def _set_attrs(xaml: str, attrs: dict[str, Any]) -> str:
            """Update multiple attributes on the <Window> tag at once."""
            # Find the end of the <Window ... > tag
            match = re.search(r'(<Window\b[^>]*>)', xaml, re.IGNORECASE | re.DOTALL)
            if not match:
                return xaml
            
            tag_content = match.group(1)
            
            for attr, value in attrs.items():
                pattern = rf'\s?\b{re.escape(attr)}\s*=\s*"[^"]*"'
                if value is None:
                    # Remove the attribute
                    tag_content = re.sub(pattern, '', tag_content)
                    continue

                # Access captions may contain & < " — escape for XML; lambda = no regex escapes
                attr_text = f'{attr}="{html.escape(str(value), quote=True)}"'
                if re.search(pattern, tag_content):
                    tag_content = re.sub(pattern, lambda _m, t=attr_text: f' {t}', tag_content)
                else:
                    # Append before the tag's closing >
                    tag_content = f'{tag_content[:-1]}\n        {attr_text}>'

            return xaml[:match.start()] + tag_content + xaml[match.end():]

        # SizeToContent ensures the window fits the Section grid perfectly (no white gaps, centering
        # relative to the content).
        attrs_to_set: dict[str, Any] = {
            "Title":                   win.get("title", form_name),
            "Background":              win.get("background") or win.get("format", {}).get("background", "#FFFFFF"),
            "WindowStyle":             win.get("window_style", "SingleBorderWindow"),
            "ResizeMode":              win.get("resize_mode", "CanResize"),
            "ShowInTaskbar":           str(win.get("show_in_taskbar", True)).capitalize(),
            "Topmost":                 str(win.get("topmost", False)).capitalize(),
            "AllowsTransparency":      "False", # Forced for stability
            "SizeToContent":           "WidthAndHeight", # 100% Match Strategy
        }
        
        # Set Startup Location
        if win.get("left") is not None and win.get("top") is not None:
            attrs_to_set["WindowStartupLocation"] = "Manual"
            attrs_to_set["Left"] = str(win.get("left"))
            attrs_to_set["Top"] = str(win.get("top"))
        else:
            attrs_to_set["WindowStartupLocation"] = win.get("startup_location", "CenterScreen")

        # Explicitly set Width and Height to None to ensure they are REMOVED from the <Window> tag
        # This is mandatory for SizeToContent="WidthAndHeight" to work.
        attrs_to_set["Width"]  = None
        attrs_to_set["Height"] = None

        xaml = _set_attrs(original, attrs_to_set)

        # ── Inject Grid content ─────────────────────────────────────────────
        # Ensure <Grid> exists
        if "<Grid" not in xaml:
            xaml = xaml.replace("</Window>", "    <Grid>\n    </Grid>\n</Window>")

        # Replace everything between <Grid> and </Grid>
        grid_inner = f"\n{grid_content}\n    " if grid_content.strip() else "\n    "
        xaml = re.sub(
            r'(<Grid[^>]*>)(.*)(</Grid>)',
            lambda m: f"{m.group(1)}{grid_inner}{m.group(3)}",
            xaml,
            flags=re.DOTALL | re.IGNORECASE,
            count=1
        )

        return xaml

    @staticmethod
    def _fix_xaml_class(xaml: str, window_name: str) -> str:
        """
        Post-process: enforce correct x:Class regardless of what LLM generated.
        Replaces any x:Class="..." with the correct vba_brain.UI.WPF.Views.{window_name}.
        """
        correct_class = f"vba_brain.UI.WPF.Views.{sanitize_class_name(window_name)}"
        fixed = re.sub(
            r'(x:Class\s*=\s*")[^"]*"',
            f'\\g<1>{correct_class}"',
            xaml,
            count=1,
        )
        if fixed == xaml and 'x:Class' not in xaml:
            fixed = xaml.replace('<Window ', f'<Window x:Class="{correct_class}" ', 1)
        if fixed != xaml:
            logger.info("[Agent UI] Fixed x:Class -> %s", correct_class)
        return fixed

    @staticmethod
    def _fix_xaml_properties(xaml: str) -> str:
        """
        Post-process: remove invalid WPF properties that LLM sometimes generates.
        - PasswordBox does NOT support: TextAlignment, Text, IsReadOnly, HorizontalContentAlignment
        """
        lines_in  = xaml.splitlines()
        lines_out = []
        in_password_box = False
        fixed_count = 0

        # Properties invalid on PasswordBox
        PB_INVALID = {"TextAlignment", "Text", "IsReadOnly"}

        for line in lines_in:
            # Start tracking when we see <PasswordBox
            if "<PasswordBox" in line:
                in_password_box = True

            # While inside PasswordBox (including opening line), strip invalid attrs
            if in_password_box:
                skip = False
                for attr in PB_INVALID:
                    if re.search(rf"\b{attr}\s*=", line):
                        logger.info("[Agent UI] Removed invalid PasswordBox attr: %s", attr)
                        fixed_count += 1
                        skip = True
                        break
                # End tracking AFTER processing this line (handles self-close on same line)
                if "/>" in line or "</PasswordBox>" in line:
                    in_password_box = False
                if skip:
                    continue

            lines_out.append(line)

        if fixed_count:
            logger.info("[Agent UI] Fixed %d invalid XAML properties", fixed_count)
        return "\n".join(lines_out)

    @staticmethod
    def _fix_xaml_canvas_to_grid(xaml: str) -> str:
        """
        Post-process: convert Canvas-based absolute layout → Grid + Margin layout.
        """
        import re as _re

        if "<Canvas" not in xaml and "Canvas.Left" not in xaml:
            return xaml

        logger.info("[Agent UI] Canvas detected — converting to Grid layout")
        xaml = _re.sub(r'<Canvas\b([^>]*)>', r'<Grid\1>', xaml)
        xaml = xaml.replace("</Canvas>", "</Grid>")

        def _convert_element(m: _re.Match) -> str:
            tag_text = m.group(0)
            left_m = _re.search(r'Canvas\.Left\s*=\s*"([^"]+)"', tag_text)
            top_m  = _re.search(r'Canvas\.Top\s*=\s*"([^"]+)"', tag_text)
            left = left_m.group(1) if left_m else "0"
            top  = top_m.group(1)  if top_m  else "0"
            tag_text = _re.sub(r'\s*Canvas\.(Left|Top)\s*=\s*"[^"]*"', "", tag_text)
            if 'HorizontalAlignment' not in tag_text:
                tag_text = _re.sub(r'(/?>)', r' HorizontalAlignment="Left"\1', tag_text, count=1)
            if 'VerticalAlignment' not in tag_text:
                tag_text = _re.sub(r'(/?>)', r' VerticalAlignment="Top"\1', tag_text, count=1)
            if 'Margin' not in tag_text:
                tag_text = _re.sub(r'(/?>)', rf' Margin="{left},{top},0,0"\1', tag_text, count=1)
            return tag_text

        xaml = _re.sub(r'<[A-Z][\w.]*(?:\s[^>]*)?>',
                      lambda m: _convert_element(m) if 'Canvas.' in m.group(0) else m.group(0),
                      xaml)
        return xaml

