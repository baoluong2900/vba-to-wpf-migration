    def _build_user_prompt(
        self,
        form_name: str,
        window_name: str,
        controls: list[dict],
        bindings: dict,
        form_config: dict,
        sections: list[dict] | None = None,
    ) -> str:
        """
        Build user prompt with all data from MongoDB.

        Sections (if present) are sent as grouped structure so LLM understands
        the parent-child hierarchy (nodekey="" = section parent, nodekey=parent = child).
        Falls back to flat controls list if no sections available.
        """
        # Background from first section's section_format
        bg_color = "#FFFFFF"
        if sections:
            bg_color = sections[0].get("section_format", {}).get("background", "#FFFFFF")

        # ── Header ──────────────────────────────────────────────────────────
        prompt  = f"Generate WPF JSONL for form: {form_name}\n"
        prompt += f"WindowName: {window_name}\n"
        prompt += f"Instructions: Output ONLY the list of UI controls (JSONL). The tool will handle the Window and ViewModel skeleton. Ensure all bindings match the 'ViewModel Bindings' section below.\n\n"

        # ── Form properties ──────────────────────────────────────────────────
        prompt += f"## Form Properties:\n```json\n{json.dumps(form_config, ensure_ascii=False, indent=2)}\n```\n\n"

        # ── UI Controls — Section-grouped (cha-con theo nodekey) ─────────────
        if sections:
            # Send sections with their children grouped — LLM sees hierarchy
            prompt += f"## UI Sections & Controls ({sum(len(s.get('controls', [])) for s in sections)} controls in {len(sections)} section(s)):\n\n"
            for sec in sections:
                sec_name   = sec.get("section_name", "__root__")
                sec_fmt    = sec.get("section_format", {})
                sec_height = sec_fmt.get("height", "")
                sec_bg     = sec_fmt.get("background", "")
                sec_type   = sec.get("section_type", "section")

                # Section header line
                prompt += f"### Section: {sec_name}"
                if sec_height: prompt += f"  (height={sec_height}px"
                if sec_bg:     prompt += f", background={sec_bg}"
                if sec_height or sec_bg: prompt += ")"
                prompt += "\n"
                
                # Output a Section object to tell LLM to include it in the response
                sec_obj = {
                    "type": "Section",
                    "name": sec_name,
                    "width": sec_fmt.get("width", 0),
                    "height": sec_height or 0,
                    "background": sec_bg or "Transparent"
                }
                prompt += json.dumps(sec_obj, ensure_ascii=False) + "\n"

                # Controls in this section — JSONL (1 line per control)
                sec_controls = sec.get("controls", [])
                if sec_controls:
                    for ctrl in sec_controls:
                        prompt += json.dumps(ctrl, ensure_ascii=False, separators=(",", ":")) + "\n"
                else:
                    prompt += "(no controls)\n"
                prompt += "\n"
        else:
            # Fallback: flat list
            controls_jsonl = "\n".join(
                json.dumps(c, ensure_ascii=False, separators=(",", ":"))
                for c in controls
            )
            prompt += f"## UI Controls ({len(controls)} items — JSONL):\n```jsonl\n{controls_jsonl}\n```\n\n"

        # ── ViewModel bindings ───────────────────────────────────────────────
        prompt += f"## ViewModel Bindings:\n"
        prompt += f"Properties: {', '.join(bindings.get('properties', []))}\n"
        prompt += f"Commands: {', '.join(bindings.get('commands', []))}\n"
        return prompt

    # ──────────────────────────────────────────
    # Token-Aware Chunking (Map-Reduce)
    # ──────────────────────────────────────────

    @staticmethod
    def _estimate_prompt_tokens(sections: list[dict]) -> int:
        """
        Rough token estimate for a list of sections.
        Rule of thumb: 1 token ≈ 3 chars of JSON.
        """
        total_chars = sum(
            len(json.dumps(ctrl, ensure_ascii=False))
            for sec in sections
            for ctrl in sec.get("controls", [])
        )
        return total_chars // 3

    @staticmethod
    def _chunk_sections(sections: list[dict], max_controls: int = CONTROLS_PER_CHUNK) -> list[list[dict]]:
        """
        Split sections list into chunks, each with at most max_controls total controls.

        Rules:
        - Prefer NOT splitting a section (keep each section whole)
        - If a single section > max_controls, split its controls into sub-chunks
          and wrap each sub-chunk as a synthetic section copy

        Returns: list of chunks, where each chunk = list[section dict]
        """
        chunks: list[list[dict]] = []
        current_chunk: list[dict] = []
        current_count = 0

        for sec in sections:
            sec_controls = sec.get("controls", [])
            n = len(sec_controls)

            if n == 0:
                # Empty section — include in current chunk (no cost)
                current_chunk.append(sec)
                continue

            if n > max_controls:
                # Section too large → split its controls into sub-chunks
                # Flush current chunk first
                if current_chunk:
                    chunks.append(current_chunk)
                    current_chunk = []
                    current_count = 0

                sec_base = {k: v for k, v in sec.items() if k != "controls"}
                for i in range(0, n, max_controls):
                    sub_controls = sec_controls[i : i + max_controls]
                    sub_sec = {**sec_base, "controls": sub_controls}
                    chunks.append([sub_sec])

            elif current_count + n > max_controls:
                # Adding this section would overflow → start new chunk
                if current_chunk:
                    chunks.append(current_chunk)
                current_chunk = [sec]
                current_count = n
            else:
                current_chunk.append(sec)
                current_count += n

        if current_chunk:
            chunks.append(current_chunk)

        return chunks

    def _call_llm_for_chunk(
        self,
        llm,
        system_prompt: str,
        chunk_idx: int,
        total_chunks: int,
        chunk_sections: list[dict],
        form_name: str,
        window_name: str,
        wpf_controls: list[dict],
        vm_bindings: dict,
        form_config: dict,
        model_override=None,
    ) -> dict:
        """
        Build prompt for a single section chunk and call LLM.
        Returns partial ui_spec dict (window + partial controls).
        """
        ctrl_count = sum(len(s.get("controls", [])) for s in chunk_sections)
        logger.info(
            "[Agent UI] Chunk %d/%d — %d controls in %d section(s)",
            chunk_idx + 1, total_chunks, ctrl_count, len(chunk_sections),
        )

        # Build prompt — same structure as _build_user_prompt but scoped to chunk
        prompt  = f"Generate WPF JSONL for form: {form_name}\n"
        prompt += f"WindowName: {window_name}\n"
        prompt += (
            f"[CHUNK {chunk_idx + 1}/{total_chunks}] "
            f"This is part {chunk_idx + 1} of {total_chunks} of a large form. "
            f"Output ONLY the controls in this chunk. "
            f"Do NOT output a 'window' object — only control/section lines.\n\n"
        )

        # Form properties (always included for context)
        prompt += f"## Form Properties:\n```json\n{json.dumps(form_config, ensure_ascii=False, indent=2)}\n```\n\n"

        # Controls in this chunk only
        chunk_ctrl_total = sum(len(s.get("controls", [])) for s in chunk_sections)
        prompt += f"## UI Sections & Controls ({chunk_ctrl_total} controls — CHUNK {chunk_idx + 1}/{total_chunks}):\n\n"

        for sec in chunk_sections:
            sec_name   = sec.get("section_name", "__root__")
            sec_fmt    = sec.get("section_format", {})
            sec_height = sec_fmt.get("height", "")
            sec_bg     = sec_fmt.get("background", "")

            prompt += f"### Section: {sec_name}"
            if sec_height: prompt += f"  (height={sec_height}px"
            if sec_bg:     prompt += f", background={sec_bg}"
            if sec_height or sec_bg: prompt += ")"
            prompt += "\n"

            sec_obj = {
                "type": "Section",
                "name": sec_name,
                "width": sec_fmt.get("width", 0),
                "height": sec_height or 0,
                "background": sec_bg or "Transparent",
            }
            prompt += json.dumps(sec_obj, ensure_ascii=False) + "\n"

            for ctrl in sec.get("controls", []):
                prompt += json.dumps(ctrl, ensure_ascii=False, separators=(",", ":")) + "\n"
            prompt += "\n"

        # ViewModel bindings
        prompt += "## ViewModel Bindings:\n"
        prompt += f"Properties: {', '.join(vm_bindings.get('properties', []))}\n"
        prompt += f"Commands: {', '.join(vm_bindings.get('commands', []))}\n"

        raw_response = llm.generate_code(
            task_type="view_xaml",
            system_prompt=system_prompt,
            user_prompt=prompt,
            model=model_override,
        )

        jsonl_raw = extract_code_block(raw_response, language="jsonl")
        # Parse but skip window object (chunk partial)
        partial_spec = self._parse_jsonl_response(jsonl_raw, window_name, form_config)
        return partial_spec

    @staticmethod
    def _merge_ui_specs(specs: list[dict]) -> dict:
        """
        Merge multiple partial ui_specs (from chunk LLM calls) into one.
        Window comes from first spec. Controls are concatenated in order.
        """
        if not specs:
            return {"window": {}, "controls": []}

        merged: dict = {
            "window":   specs[0].get("window", {}),
            "controls": [],
        }
        for spec in specs:
            merged["controls"].extend(spec.get("controls", []))

        logger.info(
            "[Agent UI] Merged %d chunks → %d total controls",
            len(specs), len(merged["controls"]),
        )
        return merged

    def _run_chunked(
        self,
        llm,
        system_prompt: str,
        form_name: str,
        window_name: str,
        wpf_controls: list[dict],
        wpf_sections: list[dict],
        vm_bindings: dict,
        form_config: dict,
        model_override=None,
    ) -> dict:
        """
        Orchestrate multi-chunk LLM calls for large forms using LangGraph StateGraph.
        """
        def split_node(state: UIChunkState) -> dict:
            chunks = self._chunk_sections(state["wpf_sections"], max_controls=CONTROLS_PER_CHUNK)
            logger.info("[Agent UI][LangGraph] Chunked form into %d chunk(s)", len(chunks))
            return {
                "chunks": chunks,
                "total_chunks": len(chunks),
                "current_idx": 0,
                "partial_specs": []
            }

        def process_chunk_node(state: UIChunkState) -> dict:
            idx = state["current_idx"]
            chunk_sections = state["chunks"][idx]
            
            try:
                partial = self._call_llm_for_chunk(
                    llm=state["llm"],
                    system_prompt=state["system_prompt"],
                    chunk_idx=idx,
                    total_chunks=state["total_chunks"],
                    chunk_sections=chunk_sections,
                    form_name=state["form_name"],
                    window_name=state["window_name"],
                    wpf_controls=state["wpf_controls"],
                    vm_bindings=state["vm_bindings"],
                    form_config=state["form_config"],
                    model_override=state["model_override"],
                )
                logger.info("[Agent UI][LangGraph] Chunk %d/%d done — %d controls parsed", 
                            idx + 1, state["total_chunks"], len(partial.get("controls", [])))
                return {
                    "partial_specs": [partial],
                    "current_idx": idx + 1
                }
            except Exception as e:
                logger.error("[Agent UI][LangGraph] Chunk %d/%d failed: %s", idx + 1, state["total_chunks"], e)
                return {
                    "current_idx": idx + 1
                }

        def merge_node(state: UIChunkState) -> dict:
            partial_specs = state["partial_specs"]
            if not partial_specs:
                raise RuntimeError(f"[Agent UI][LangGraph] All chunks failed for form {state['form_name']}")
            final_spec = self._merge_ui_specs(partial_specs)
            return {"final_spec": final_spec}

        def should_continue(state: UIChunkState) -> str:
            if state["current_idx"] < state["total_chunks"]:
                return "process_chunk_node"
            return "merge_node"

        # Build Graph
        builder = StateGraph(UIChunkState)
        builder.add_node("split_node", split_node)
        builder.add_node("process_chunk_node", process_chunk_node)
        builder.add_node("merge_node", merge_node)

        builder.add_edge(START, "split_node")
        builder.add_edge("split_node", "process_chunk_node")
        builder.add_conditional_edges("process_chunk_node", should_continue)
        builder.add_edge("merge_node", END)

        graph = builder.compile()

        # Initialize State
        initial_state: UIChunkState = {
            "form_name": form_name,
            "window_name": window_name,
            "wpf_controls": wpf_controls,
            "wpf_sections": wpf_sections,
            "vm_bindings": vm_bindings,
            "form_config": form_config,
            "system_prompt": system_prompt,
            "model_override": model_override,
            "llm": llm,
            "chunks": [],
            "total_chunks": 0,
            "current_idx": 0,
            "partial_specs": [],
            "final_spec": {}
        }

        logger.info("[Agent UI][LangGraph] Invoking map-reduce graph for %s...", form_name)
        final_state = graph.invoke(initial_state)
        return final_state["final_spec"]

