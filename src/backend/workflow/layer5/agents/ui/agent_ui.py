    def _save_output(
        self,
        form_name: str,
        window_name: str,
        xaml: str,
        cs: str = "",
        vm: str = "",
        view_file_stem: str | None = None,
        vm_file_stem: str | None = None,
    ) -> None:
        """
        Save all generated files to outputs/ (auto-copied to WPF source by route.ts).
        
        Args:
            form_name: JP form name (for folder naming)
            window_name: JP window name (for reference)
            xaml, cs, vm: generated code
            view_file_stem: EN view name (e.g. "AMRequestPrintPDFView") — used for file naming
            vm_file_stem: EN viewmodel name (e.g. "AMRequestPrintPDFViewModel") — used for file naming
        """
        out_dir = OUTPUTS_DIR / form_name
        out_dir.mkdir(parents=True, exist_ok=True)
        
        # Use EN names if provided, fallback to window_name
        view_name = view_file_stem if view_file_stem else window_name
        vm_name   = vm_file_stem if vm_file_stem else (window_name.replace("Window", "ViewModel"))

        # Subfolders inside form folder
        views_dir = out_dir / "Views"
        vms_dir   = out_dir / "ViewModels"
        views_dir.mkdir(exist_ok=True)
        vms_dir.mkdir(exist_ok=True)

        xaml_path = views_dir / f"{view_name}.xaml"
        cs_path   = views_dir / f"{view_name}.xaml.cs"
        vm_path   = vms_dir   / f"{vm_name}.cs"

        # Cleanup old JP-named files if EN name is different to prevent duplicates in outputs folder
        if view_name != window_name:
            old_xaml = views_dir / f"{window_name}.xaml"
            old_cs   = views_dir / f"{window_name}.xaml.cs"
            if old_xaml.exists(): old_xaml.unlink()
            if old_cs.exists():   old_cs.unlink()
        
        old_vm_name = window_name.replace("Window", "ViewModel")
        if vm_name != old_vm_name:
            old_vm = vms_dir / f"{old_vm_name}.cs"
            if old_vm.exists(): old_vm.unlink()

        xaml_path.write_text(xaml, encoding="utf-8")
        logger.info("[Agent UI] Saved: %s", xaml_path.name)

        if cs:
            cs_path.write_text(cs, encoding="utf-8")
            logger.info("[Agent UI] Saved: %s", cs_path.name)

        if vm:
            vm_path.write_text(vm, encoding="utf-8")
            logger.info("[Agent UI] Saved: ViewModels/%s", vm_path.name)

    def fix_build_errors(self, window_name: str, build_errors: str) -> dict[str, str]:
        """
        AI-powered build error fixer.
        Reads current outputs/, sends to LLM with errors, returns fixed file contents.
        Returns: {"xaml": fixed_xaml, "cs": fixed_cs}
        """
        xaml_path = OUTPUTS_DIR / f"{window_name}.xaml"
        cs_path   = OUTPUTS_DIR / f"{window_name}.xaml.cs"

        current_xaml = xaml_path.read_text(encoding="utf-8") if xaml_path.exists() else ""
        current_cs   = cs_path.read_text(encoding="utf-8")   if cs_path.exists()   else ""

        has_cs_err = ".xaml.cs" in build_errors or "CS0" in build_errors

        system_prompt = self.load_prompt("agent_ui_fix.md")
        llm = L5LLMClient()
        result: dict[str, str] = {}

        # Fix XAML
        if current_xaml and not has_cs_err:
            user_prompt = (
                f"## Build Errors:\n```\n{build_errors}\n```\n\n"
                f"## Current {window_name}.xaml:\n```xml\n{current_xaml}\n```\n\n"
                "Fix ONLY the errors above. Return the complete fixed XAML."
            )
            raw = llm.generate_code(task_type="view_xaml", system_prompt=system_prompt, user_prompt=user_prompt)
            fixed_xaml = extract_code_block(raw, language="xml")
            fixed_xaml = self._fix_xaml_class(fixed_xaml, window_name)
            fixed_xaml = self._fix_xaml_properties(fixed_xaml)
            fixed_xaml = self._fix_xaml_canvas_to_grid(fixed_xaml)
            xaml_path.write_text(fixed_xaml, encoding="utf-8")
            result["xaml"] = fixed_xaml
            logger.info("[Agent UI] Fixed XAML: %s", xaml_path.name)

        # Fix CS
        if current_cs and has_cs_err:
            user_prompt = (
                f"## Build Errors:\n```\n{build_errors}\n```\n\n"
                f"## Current {window_name}.xaml.cs:\n```csharp\n{current_cs}\n```\n\n"
                "Fix ONLY the errors above. Return the complete fixed C# code."
            )
            raw = llm.generate_code(task_type="view_xaml", system_prompt=system_prompt, user_prompt=user_prompt)
            fixed_cs = extract_code_block(raw, language="csharp")
            cs_path.write_text(fixed_cs, encoding="utf-8")
            result["cs"] = fixed_cs
            logger.info("[Agent UI] Fixed CS: %s", cs_path.name)

        return result


