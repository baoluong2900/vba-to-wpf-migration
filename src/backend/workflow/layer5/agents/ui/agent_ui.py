def _load_form_name_map() -> dict[str, dict]:
    """
    Load listFormJpToEn.json and return a dict keyed by access_form_name.
    Returns {} if file not found.
    Example:
        "AM依頼_印刷_PDF" → {
            "wpf_view_name":      "AMRequestPrintPDFView",
            "wpf_viewmodel_name": "AMRequestPrintPDFViewModel"
        }
    """
    if not _FORM_JP_TO_EN_PATH.exists():
        logger.warning("[Agent UI] listFormJpToEn.json not found at %s", _FORM_JP_TO_EN_PATH)
        return {}
    try:
        data = json.loads(_FORM_JP_TO_EN_PATH.read_text(encoding="utf-8"))
        return {item["access_form_name"]: item for item in data.get("items", [])}
    except Exception as exc:
        logger.warning("[Agent UI] Failed to load listFormJpToEn.json: %s", exc)
        return {}


def _resolve_wpf_names(form_name: str, name_map: dict[str, dict]) -> tuple[str, str]:
    """
    Resolve WPF View and ViewModel class names from JP form name.

    Rules:
      1. Lookup listFormJpToEn.json by access_form_name
      2. Strip trailing "View" suffix for the bare class name used in file naming
         e.g. "AMRequestPrintPDFView" → file = "AMRequestPrintPDFView.xaml"
              "AMRequestPrintPDFViewModel" → file = "AMRequestPrintPDFViewModel.cs"
      3. Fallback: use sanitize_class_name(form_name) if not in map

    Returns:
        (view_class_name, viewmodel_class_name)
        e.g. ("AMRequestPrintPDFView", "AMRequestPrintPDFViewModel")
    """
    entry = name_map.get(form_name)
    if entry:
        view_name = entry.get("wpf_view_name", "")
        vm_name   = entry.get("wpf_viewmodel_name", "")
        if view_name and vm_name:
            return view_name, vm_name

    # Fallback: sanitize the JP name
    fallback = sanitize_class_name(form_name)
    logger.debug(
        "[Agent UI] form_name %r not in JP→EN map — fallback class name: %r",
        form_name, fallback,
    )
    return fallback, fallback + "ViewModel"

# ──────────────────────────────────────────────
# Token-aware chunking config
# Output token budget per LLM call: ~16K max (Qwen 16K max output)
# Each control output ≈ 80-120 tokens → 120 controls ≈ 10K-14K tokens (safe margin)
# ──────────────────────────────────────────────
CONTROLS_PER_CHUNK = 120  # max controls per single LLM call
CHUNK_THRESHOLD    = 150  # forms with more controls than this → auto-chunk


class UIAgent(BaseAgent):
    """
    Agent UI — Generate WPF XAML View.
    Data source: MongoDB `forms` collection only.
    """

    @property
    def name(self) -> str:
        return "ui"

    async def run(self, input: AgentInput) -> AgentOutput:
        form_name = input.form_name
        
        # ── Resolve WPF class names (EN) from JP form name ──────────────────
        _name_map = _load_form_name_map()
        wpf_view_name, wpf_viewmodel_name = _resolve_wpf_names(form_name, _name_map)
        # view_file_stem: bare name used for .xaml / .xaml.cs files (e.g. "AMRequestPrintPDFView")
        # vm_file_stem:   bare name used for ViewModel .cs file     (e.g. "AMRequestPrintPDFViewModel")
        view_file_stem = wpf_view_name       # e.g. "AMRequestPrintPDFView"
        vm_file_stem   = wpf_viewmodel_name  # e.g. "AMRequestPrintPDFViewModel"
        logger.info(
            "[Agent UI] Name mapping: %r → view=%r, vm=%r",
            form_name, view_file_stem, vm_file_stem,
        )
        
        # ── Setup LLM config based on override ──────────────────────────
        model_override = input.model_override
        if isinstance(model_override, str):
            model_override = AVAILABLE_MODELS.get(model_override)
        
        logger.info("[Agent UI] Starting for form: %s (model: %s)", 
                    form_name, getattr(model_override, 'model_id', 'default'))

        try:
            # ── Step 1: Query MongoDB forms collection ──────────────────
            mongo_data = input.mongodb_data or self._load_mongo_form(form_name)

            # ── Step 2: Extract controls from MongoDB items[] ───────────
            mongo_items = mongo_data.get("items", [])
            form_props  = mongo_data.get("properties", {})   # top-level properties

            # ── Step 3: Map Access controls → WPF controls ──────────────
            wpf_controls = map_all_controls(mongo_items)      # flat → for LLM prompt
            wpf_sections = map_sections(mongo_items)           # grouped → for input snapshot
            logger.info("[Agent UI] Mapped %d WPF controls", len(wpf_controls))

            # ── Step 3b: Extract control_source query stubs ──────────────
            # Gen ui_query_stubs.json — contract cho Logic Agent
            _qstub_tool  = QueryStubTool()
            _query_stubs = _qstub_tool.extract(form_name, wpf_controls)
            if _query_stubs:
                _qstub_tool.save(form_name, _query_stubs)
                logger.info("[Agent UI] Query stubs: %d control_source(s) extracted", len(_query_stubs))

            # ── Step 4: Get ViewModel bindings ──────────────────────────
            form_events  = form_props.get("event", {})
            vm_bindings  = self._get_viewmodel_bindings(
                input, form_name, wpf_controls, form_events, _query_stubs
            )

            # ── Step 4b: Remap command names to F-ID (e.g. 閉じるCommand → F004Command) ──
            # This ensures XAML binding names match the ViewModel property names generated
            # by tool_skeleton.py (which uses F-ID naming for all commands).
            vm_bindings = self._remap_commands_to_fid(form_name, vm_bindings)

            # ── Step 5: Build form-level config from MongoDB ────────────
            form_config = self._build_form_config(form_props, wpf_sections)
            
            # ── Step 5b: Sync section widths with form inner width to prevent misalignment ──
            inner_width = form_config.get("inner_width", 0)
            if inner_width > 0:
                for sec in wpf_sections:
                    sec["section_format"]["width"] = inner_width

            # ── Step 6: Save input snapshot ─────────────────────────────
            input_snapshot = {
                "form_name":          form_name,
                "form_properties":    form_config,
                "sections":           wpf_sections,    # grouped by section + full format
                "viewmodel_bindings": vm_bindings,
            }
            self._save_input(form_name, input_snapshot, view_file_stem=view_file_stem)

            # ── Step 7: Build prompt and call LLM ───────────────────────
            # form_name IS the window name (e.g. F_Login → F_Login.xaml already exists)
            window_name   = form_name
            system_prompt = self._build_system_prompt()

            # ── Step 7b: Auto-detect chunked mode ───────────────────────
            total_controls = sum(len(s.get("controls", [])) for s in wpf_sections)
            llm = L5LLMClient()

            if total_controls > CHUNK_THRESHOLD:
                logger.info(
                    "[Agent UI] Large form: %d controls > threshold %d → CHUNKED mode",
                    total_controls, CHUNK_THRESHOLD,
                )
                ui_spec = self._run_chunked(
                    llm=llm,
                    system_prompt=system_prompt,
                    form_name=form_name,
                    window_name=window_name,
                    wpf_controls=wpf_controls,
                    wpf_sections=wpf_sections,
                    vm_bindings=vm_bindings,
                    form_config=form_config,
                    model_override=model_override,
                )
            else:
                logger.info(
                    "[Agent UI] Small form: %d controls ≤ threshold %d → SINGLE-CALL mode",
                    total_controls, CHUNK_THRESHOLD,
                )
                user_prompt = self._build_user_prompt(
                    form_name, window_name, wpf_controls, vm_bindings, form_config, wpf_sections
                )
                raw_response = llm.generate_code(
                    task_type="view_xaml",
                    system_prompt=system_prompt,
                    user_prompt=user_prompt,
                    model=model_override,
                )

                # ── Step 8: Parse JSONL from LLM ────────────────────────
                jsonl_raw = extract_code_block(raw_response, language="jsonl")
                ui_spec   = self._parse_jsonl_response(jsonl_raw, window_name, form_config)

            # Re-inject 'picture', 'background', 'border_brush' field from original controls (LLM often drops them)
            orig_styles = {
                c["name"]: {
                    "picture":      c["format"].get("picture"),
                    "background":   c["format"].get("background"),
                    "border_brush": c["format"].get("border_brush") or c["format"].get("border_color"),
                } 
                for c in wpf_controls
            }

            # Build set of image files that ACTUALLY EXIST in WPF Resources.
            # FRM importer sometimes skips PictureData → imagedata not stored in MongoDB
            # → control_mapper cannot set picture. We compensate here by filesystem scan.
            _img_res_dir = WPF_VIEWS_DIR.parent / "Resources" / "img" / form_name
            _available_imgs: set[str] = set()
            if _img_res_dir.is_dir():
                for _f in _img_res_dir.iterdir():
                    if _f.suffix.lower() in (".bmp", ".png", ".jpg", ".ico"):
                        _available_imgs.add(_f.name)  # e.g. "cmdFirst.bmp"
            if _available_imgs:
                logger.info(
                    "[Agent UI] Found %d image(s) in Resources/img/%s: %s",
                    len(_available_imgs), form_name, sorted(_available_imgs),
                )

            def inject_styles(ctrls):
                for ctrl in ctrls:
                    name = ctrl.get("name")
                    if name in orig_styles:
                        style = orig_styles[name]
                        if style.get("picture") and "picture" not in ctrl:
                            ctrl["picture"] = style["picture"]
                        if style.get("background") and "background" not in ctrl:
                            ctrl["background"] = style["background"]
                        if style.get("border_brush") and "border_brush" not in ctrl:
                            ctrl["border_brush"] = style["border_brush"]

                    # Filesystem fallback: MongoDB missed PictureData → check Resources/img/
                    # Try {name}.bmp and {name}.png (extractor convention)
                    if name and "picture" not in ctrl:
                        for _ext in (".bmp", ".png"):
                            _candidate = f"{name}{_ext}"
                            if _candidate in _available_imgs:
                                ctrl["picture"] = _candidate
                                logger.debug(
                                    "[Agent UI] picture fallback (fs): %s → %s",
                                    name, _candidate,
                                )
                                break

                    if "controls" in ctrl:
                        inject_styles(ctrl["controls"])

            inject_styles(ui_spec.get("controls", []))

            # ── Remap command names trong controls: 閉じるCommand → F004Command ──
            # LLM gen command field dựa theo tên cũ (tên Nhật/VBA), cần map sang F-ID
            # để khớp với ViewModel property được gen bởi tool_skeleton.
            _fid_cmd_map: dict[str, str] = vm_bindings.get("fid_cmd_map", {})
            if _fid_cmd_map:
                def _remap_ctrl_commands(ctrls: list) -> None:
                    for c in ctrls:
                        old_cmd = c.get("command", "")
                        if old_cmd and old_cmd in _fid_cmd_map:
                            c["command"] = _fid_cmd_map[old_cmd]
                            logger.debug(
                                "[Agent UI] Remap command: %s → %s (ctrl: %s)",
                                old_cmd, _fid_cmd_map[old_cmd], c.get("name", "?"),
                            )
                        if "controls" in c:
                            _remap_ctrl_commands(c["controls"])
                _remap_ctrl_commands(ui_spec.get("controls", []))
                logger.info(
                    "[Agent UI] Remapped command bindings in %d control(s) using fid_cmd_map",
                    sum(1 for c in ui_spec.get("controls", []) if c.get("command") in _fid_cmd_map.values()),
                )

            # ── Step 8b: Save preview JSON for user review ───────────────
            self._save_preview_json(form_name, ui_spec, view_file_stem=view_file_stem)
            logger.info("[Agent UI] Preview JSON saved → outputs/%s_preview.json", form_name)

            # ── Step 8c: Assemble XAML from JSON (deterministic) ─────────
            # Build event_handler_map: ctrl_name → {vba_event: cs_method_fid}
            # cs_method phải dùng F-ID naming (F005_DblClick) để khớp với code-behind.
            # KHÔNG dùng tên VBA gốc (施工店情報_DblClick) — gây lỗi compiler.
            from agents.ui.tool_skeleton import _resolve_vba_to_module_id_map, get_cs_handler_name

            _all_handlers = [
                h.get("method", "")
                for h in vm_bindings.get("event_handlers", [])
                if h.get("method") and not h.get("synthetic")
            ]
            _vba_mid_map = _resolve_vba_to_module_id_map(form_name, _all_handlers)

            event_handler_map: dict[str, dict[str, str]] = {}
            for hdlr in vm_bindings.get("event_handlers", []):
                ctrl_name = hdlr.get("control", "")
                vba_event = hdlr.get("event", "")
                vba_method = hdlr.get("method", "")

                # Skip form-level and synthetic handlers — không wire vào control XAML
                if not ctrl_name or ctrl_name == "__form__" or hdlr.get("synthetic"):
                    continue
                if not vba_event or not vba_method:
                    continue

                # Resolve sang F-ID cs_method: F005_DblClick, F004_Click, etc.
                module_id = _vba_mid_map.get(vba_method, "")
                if module_id:
                    cs_method = get_cs_handler_name(module_id, vba_event)
                else:
                    cs_method = vba_method  # fallback nếu chưa có F-ID

                event_handler_map.setdefault(ctrl_name, {})[vba_event] = cs_method

            grid_content = self._jsonl_to_grid_content(
                ui_spec.get("controls", []), form_name, event_handler_map, _vba_mid_map
            )

            # ── Step 9: Inject into existing skeleton .xaml ───────────────
            # Đọc skeleton từ tên gốc (JP) nếu tồn tại, fallback về tên EN mới
            source_file = WPF_VIEWS_DIR / f"{form_name}.xaml"
            if not source_file.exists():
                source_file = WPF_VIEWS_DIR / f"{view_file_stem}.xaml"
            xaml_code    = self._inject_into_skeleton(
                source_file, ui_spec, form_name, grid_content
            )
            # ── Enforce correct x:Class = view_file_stem (EN name) ──────────
            # Skeleton may still carry old JP-based x:Class (e.g. F_Login).
            # _fix_xaml_class replaces it with vba_brain.UI.WPF.Views.{view_file_stem}
            # so XAML and code-behind partial class always match.
            xaml_code = self._fix_xaml_class(xaml_code, view_file_stem)

            # ── Step 8d: Generate Code-behind and ViewModel (deterministic — zero LLM token) ──
            # Pass wpf_view_name/wpf_viewmodel_name so generated class names are English
            _skeleton = SkeletonTool()
            cs_code   = _skeleton.gen_codebehind(
                form_name, vm_bindings,
                class_name_override=view_file_stem,
                vm_class_name_override=vm_file_stem,
            )
            vm_code   = _skeleton.gen_viewmodel(form_name, vm_bindings, class_name_override=vm_file_stem)

            # ── Step 10: Save to outputs/ (for review) + source files ─────
            self._save_output(
                form_name, form_name, xaml_code, cs_code, vm_code,
                view_file_stem=view_file_stem,
                vm_file_stem=vm_file_stem,
            )

            # Ghi thẳng vào WPF source (Views/ and ViewModels/) — dùng tên EN
            xaml_source = WPF_VIEWS_DIR / f"{view_file_stem}.xaml"
            cs_source   = WPF_VIEWS_DIR / f"{view_file_stem}.xaml.cs"
            vm_dir      = WPF_VIEWS_DIR.parent / "ViewModels"
            vm_source   = vm_dir / f"{vm_file_stem}.cs"

            if xaml_source.parent.exists():
                xaml_source.write_text(xaml_code, encoding="utf-8")
                logger.info("[Agent UI] Updated XAML: %s", xaml_source.name)

                # Xóa file tên JP cũ nếu khác với tên EN mới (tránh duplicate)
                old_xaml = WPF_VIEWS_DIR / f"{form_name}.xaml"
                old_cs   = WPF_VIEWS_DIR / f"{form_name}.xaml.cs"
                if old_xaml != xaml_source and old_xaml.exists():
                    old_xaml.unlink()
                    logger.info("[Agent UI] Removed old JP-named file: %s", old_xaml.name)
                if old_cs != cs_source and old_cs.exists():
                    old_cs.unlink()
                    logger.info("[Agent UI] Removed old JP-named file: %s", old_cs.name)

            cs_source.parent.mkdir(parents=True, exist_ok=True)
            cs_source.write_text(cs_code, encoding="utf-8")

            vm_dir.mkdir(parents=True, exist_ok=True)
            vm_source.write_text(vm_code, encoding="utf-8")

            # Xóa ViewModel tên JP cũ nếu khác
            old_vm = vm_dir / f"{form_name}.cs"
            if old_vm != vm_source and old_vm.exists():
                old_vm.unlink()
                logger.info("[Agent UI] Removed old JP-named ViewModel: %s", old_vm.name)

            files_out = [
                GeneratedFile(path=f"Views/{view_file_stem}.xaml",    content=xaml_code,  generator="jsonl",    agent="ui"),
                GeneratedFile(path=f"Views/{view_file_stem}.xaml.cs", content=cs_code,    generator="template", agent="ui"),
                GeneratedFile(path=f"ViewModels/{vm_file_stem}.cs",   content=vm_code,    generator="template", agent="ui"),
            ]

            output = AgentOutput(
                agent="ui",
                form_name=form_name,
                files=files_out,
                status="success",
                metadata={
                    "window_name":       form_name,
                    "wpf_view_name":     view_file_stem,
                    "wpf_viewmodel_name":vm_file_stem,
                    "controls_count":    len(ui_spec.get("controls", [])),
                    "bindings":          vm_bindings,
                    "preview_json":      f"{form_name}_preview.json",
                },
            )

            logger.info(
                "[Agent UI] Generated %d files for %s",
                len(files_out), form_name,
            )

            # ── Auto Backup ──
            try:
                import sys
                layer5_dir = str(Path(__file__).resolve().parent.parent.parent)
                if layer5_dir not in sys.path:
                    sys.path.insert(0, layer5_dir)
                from pipeline import backup_layer5
                backup_layer5.backup_agent(self.name)
            except Exception as exc:
                logger.error("Auto-backup failed: %s", exc)

            return output


        except Exception as e:
            logger.error("[Agent UI] Failed for %s: %s", form_name, e, exc_info=True)
            return AgentOutput(
                agent="ui",
                form_name=form_name,
                status="error",
                error=str(e),
            )

    # ──────────────────────────────────────────
    # MongoDB Data Loader
    # ──────────────────────────────────────────

    def _load_mongo_form(self, form_name: str) -> dict:
        """Query form data from MongoDB `forms` collection."""
        from pymongo import MongoClient

        client = MongoClient(MONGO_URI)
        db     = client[MONGO_DB]
        doc    = db["forms"].find_one({"name": form_name})
        client.close()

        if not doc:
            raise ValueError(f"Form '{form_name}' not found in MongoDB `forms` collection")

        doc["_id"] = str(doc["_id"])
        return doc

    # ──────────────────────────────────────────
    # Form Config (from MongoDB forms.properties)
    # ──────────────────────────────────────────

    def _build_form_config(self, form_props: dict, sections: list[dict] | None = None) -> dict:
        """Extract form-level config entirely from MongoDB forms.properties."""
        fmt   = form_props.get("format", {})
        other = form_props.get("other", {})
        event = form_props.get("event", {})

        # Use exact design dimensions for the "Inner" content
        # This ensures 100% match with the design surface
        inner_width_px = twips_to_px(fmt.get("width", 5000))
        
        total_height_px = 0
        if sections:
            for sec in sections:
                total_height_px += sec.get("section_format", {}).get("height", 0)
        
        # We will use SizeToContent="WidthAndHeight" in the XAML, 
        # so we don't need to guess final_width/height anymore.
        # We just pass the inner dimensions to the generator.
        return {
            "caption":      fmt.get("caption", ""),
            "width":        None, # SizeToContent will handle this
            "height":       None, # SizeToContent will handle this
            "inner_width":  inner_width_px,
            "inner_height": total_height_px or 180,
            "left":         int(fmt.get("left", 0) / 15.0),
            "top":          int(fmt.get("top", 0) / 15.0),
            "popup":        other.get("popup",       False),
            "modal":        other.get("modal",       False),
            "autocenter":   fmt.get("autocenter",    False),
            "border_style": fmt.get("border_style", 3),
            "maxbutton":    fmt.get("maxbutton",     True),
            "minbutton":    fmt.get("minbutton",     True),
            "closebutton":  fmt.get("closebutton",   True),
            "controlbox":   fmt.get("controlbox",    True),
            "scrollbars":   fmt.get("scrollbars",    0),
            "borderstyle":  fmt.get("borderstyle",   1),
            "moveable":     fmt.get("moveable",      1),
            "fittoscreen":  fmt.get("fittoscreen",   0),
            "events":       {k: v for k, v in event.items() if v},
        }

    # ──────────────────────────────────────────
    # ViewModel Bindings
    # ──────────────────────────────────────────

    def _get_viewmodel_bindings(
        self,
        input: AgentInput,
        form_name: str,
        wpf_controls: list[dict],
        form_events: dict | None = None,
        query_stubs: dict[str, dict] | None = None,
    ) -> dict:
        """
        Get ViewModel bindings:
        1. From upstream Agent Logic output (preferred)
        2. From saved JSON in inputs/
        3. Infer from wpf_controls events + form_events (MongoDB data — no BD JSON needed)
        """
        # Check upstream files for ViewModel
        for uf in input.upstream_files:
            if "ViewModel" in uf.path and uf.path.endswith(".cs"):
                return self._extract_bindings_from_viewmodel(uf.content)

        # Check inputs/ folder
        vm_file = INPUTS_DIR / f"{form_name}_viewmodel_bindings.json"
        if vm_file.exists():
            return json.loads(vm_file.read_text(encoding="utf-8"))

        # Fallback: infer from wpf_controls events + form-level events (MongoDB data)
        return self._infer_bindings_from_controls(
            wpf_controls, form_events or {}, query_stubs or {}
        )

    def _remap_commands_to_fid(self, form_name: str, vm_bindings: dict) -> dict:
        """
        Remap command names in vm_bindings from JP/VBA-based names to F-ID names.
        e.g. 閉じるCommand → F004Command, LoginCommand → F006Command

        This keeps XAML bindings consistent with ViewModel property names
        generated by tool_skeleton.py.

        Also stores `fid_cmd_map` for reference: {old_name → fid_name}
        """
        from agents.ui.tool_skeleton import _resolve_vba_to_module_id_map

        event_handlers = vm_bindings.get("event_handlers", [])
        commands       = vm_bindings.get("commands", [])

        if not commands or not event_handlers:
            return vm_bindings

        # Resolve vba_handler → module_id via ui_event_map.json
        all_handlers = [h.get("method", "") for h in event_handlers if h.get("method")]
        vba_mid_map: dict[str, str] = _resolve_vba_to_module_id_map(form_name, all_handlers)

        # Build old_cmd_key → fid_cmd mapping (same logic as tool_skeleton.gen_viewmodel)
        old_to_fid: dict[str, str] = {}
        for hdlr in event_handlers:
            method = hdlr.get("method", "")
            ctrl   = hdlr.get("control", "")
            if not method:
                continue
            base = (method
                    .replace("_Click", "").replace("_DblClick", "")
                    .replace("_Dbl", "").replace("_AfterUpdate", ""))
            if ctrl and ctrl.startswith("cmd") and base == ctrl:
                base = ctrl[3:]
            old_cmd = base + "Command"
            if old_cmd in commands:
                mid = vba_mid_map.get(method, "")
                if mid:
                    old_to_fid[old_cmd] = f"{mid}Command"

        if not old_to_fid:
            return vm_bindings

        # Remap and sort
        def _fid_sort_key(cmd: str) -> tuple[int, str]:
            import re as _re
            m = _re.match(r'^F(\d+)Command$', cmd)
            return (int(m.group(1)), cmd) if m else (9999, cmd)

        new_commands: list[str] = []
        seen: set[str] = set()
        for c in commands:
            fid = old_to_fid.get(c, c)
            if fid not in seen:
                new_commands.append(fid)
                seen.add(fid)
        new_commands.sort(key=_fid_sort_key)

        vm_bindings = {**vm_bindings, "commands": new_commands, "fid_cmd_map": old_to_fid}
        logger.debug("[Agent UI] Remapped %d commands to F-ID: %s", len(old_to_fid), old_to_fid)
        return vm_bindings

    def _extract_bindings_from_viewmodel(self, cs_code: str) -> dict:
        """Parse C# ViewModel to extract properties and commands."""
        properties: list[str] = []
        commands:   list[str] = []

        for m in re.finditer(r'public\s+\w+\??\s+(\w+)\s*\{', cs_code):
            name = m.group(1)
            if name.endswith("Command"):
                commands.append(name)
            elif not name.startswith("_"):
                properties.append(name)

        for m in re.finditer(r'public\s+(?:Relay|Async)?Command\s+(\w+)', cs_code):
            cmd = m.group(1)
            if cmd not in commands:
                commands.append(cmd)

        return {"properties": properties, "commands": commands}

    def _infer_bindings_from_controls(
        self,
        wpf_controls: list[dict],
        form_events: dict | None = None,
        query_stubs: dict[str, dict] | None = None,
    ) -> dict:
        """
        Infer ViewModel bindings from wpf_controls events + form-level events (MongoDB data).
        No BD JSON needed.
        Returns: {properties, commands, event_handlers, query_stubs}
          event_handlers: list of {"method": str, "event": str, "control": str}
          query_stubs:    dict[control_name → stub] từ tool_query_stubs.py

        form_events:  dict from forms.properties.event e.g. {"onopen": "Form_Open", ...}
        query_stubs:  dict từ QueryStubTool.extract() — suggested_property per control
        """
        properties:     list[str]  = []
        commands:       list[str]  = []
        event_handlers: list[dict] = []
        seen_props: set[str] = set()
        seen_cmds:  set[str] = set()
        seen_hdlrs: set[str] = set()
        _stubs = query_stubs or {}

        # ── Form-level events first (F000, F001, F002...) ───────────────────
        # VBA form event → WPF event name + C# EventArgs type
        FORM_EVENT_ARGS: dict[str, tuple[str, str]] = {
            "onopen":    ("Loaded",          "RoutedEventArgs"),
            "onload":    ("ContentRendered",  "EventArgs"),
            "onclose":   ("Closed",           "EventArgs"),
            "onkeydown": ("PreviewKeyDown",   "KeyEventArgs"),
            "onkeyup":   ("PreviewKeyUp",     "KeyEventArgs"),
            "onresize":  ("SizeChanged",      "SizeChangedEventArgs"),
            "onactivate":("Activated",        "EventArgs"),
        }
        for vba_evt, handler_name in (form_events or {}).items():
            if not handler_name:
                continue
            evt_key = vba_evt.lower()
            wpf_event, args = FORM_EVENT_ARGS.get(evt_key, (vba_evt, "RoutedEventArgs"))
            if handler_name not in seen_hdlrs:
                event_handlers.append({
                    "method":       handler_name,
                    "event":        vba_evt,         # e.g. "onopen"
                    "wpf_event":    wpf_event,        # e.g. "Loaded"
                    "control":      "__form__",       # sentinel: form-level, not a control
                    "args":         args,
                    "todo":         "",
                })
                seen_hdlrs.add(handler_name)

        # VBA event → C# EventArgs type mapping
        EVENT_ARGS: dict[str, str] = {
            "onclick":       "RoutedEventArgs",
            "click":         "RoutedEventArgs",
            "ondblclick":    "MouseButtonEventArgs",
            "dblclick":      "MouseButtonEventArgs",
            "onkeydown":     "KeyEventArgs",
            "onkeyup":       "KeyEventArgs",
            "onkeypress":    "KeyEventArgs",
            "onchange":      "RoutedEventArgs",
            "ongotfocus":    "RoutedEventArgs",
            "onlostfocus":   "RoutedEventArgs",
            "onenter":       "RoutedEventArgs",
            "onexit":        "RoutedEventArgs",
            "afterupdate":   "RoutedEventArgs",
            "beforeupdate":  "RoutedEventArgs",
        }

        for ctrl in wpf_controls:
            name     = ctrl.get("name", "")
            wpf_type = ctrl.get("wpf_type", "")
            events   = ctrl.get("events", {})

            # ─ Property binding inference ────────────────────────────────
            # Rules (không gen bừa):
            #   1. is_readonly: true → display-only, KHÔNG cần ViewModel property
            #   2. PasswordBox     → luôn dùng "Password" (chuẩn WPF MVVM)
            #   3. TextBox writable + starts with "txt" → strip prefix làm property name
            #   4. control_source → dùng suggested_property từ query_stubs nếu có,
            #                       fallback tự parse expression
            is_readonly = ctrl.get("data", {}).get("is_readonly", False)
            control_source = ctrl.get("data", {}).get("control_source", "")

            # Infer property from control_source
            if control_source and wpf_type in ("TextBox", "Label", "TextBlock"):
                # Ưu tiên suggested_property từ QueryStubTool (đã parse đúng)
                stub = _stubs.get(name)
                if stub and stub.get("suggested_property"):
                    prop = stub["suggested_property"]
                    if prop not in seen_props:
                        properties.append(prop)
                        seen_props.add(prop)
                elif control_source.startswith("="):
                    # Expression fallback: extract field names
                    import re
                    fields = re.findall(r'\[([^\]]+)\]', control_source)
                    if fields:
                        prop = "".join(fields) + "表示"
                        if prop not in seen_props:
                            properties.append(prop)
                            seen_props.add(prop)
                else:
                    # Simple field reference
                    prop = control_source
                    if prop not in seen_props:
                        properties.append(prop)
                        seen_props.add(prop)

            if wpf_type == "PasswordBox" and not is_readonly:
                # PasswordBox → derive property name from control name (e.g. txtPass -> Pass)
                prop = (name.replace("txt", "", 1) if name.startswith("txt") else name)
                if not prop: prop = "Password"
                
                if prop not in seen_props:
                    properties.append(prop)
                    seen_props.add(prop)
                
                # Store mapping for tool_skeleton to generate unique handlers
                if "password_mappings" not in locals(): # This won't work in a loop, need to init outside
                    pass 


            # Button → Command binding
            # Chỉ gen từ Button name nếu KHÔNG có onclick event
            if wpf_type == "Button" and "onclick" not in events and "click" not in events:
                # Skip nếu button bị ẩn (Visibility="Collapsed") — không cần Command
                is_hidden = ctrl.get("visible") is False or ctrl.get("format", {}).get("visible") is False
                if is_hidden:
                    continue
                physical_name_btn = ctrl.get("data", {}).get("physical_name", "") or name
                cmd = (physical_name_btn.replace("cmd", "", 1) + "Command"
                       if physical_name_btn.startswith("cmd") else physical_name_btn + "Command")
                if cmd not in seen_cmds:
                    commands.append(cmd)
                    seen_cmds.add(cmd)
                synthetic_method = physical_name_btn + "_Click"
                if synthetic_method not in seen_hdlrs:
                    event_handlers.append({
                        "method":    synthetic_method,
                        "event":     "onclick",
                        "control":   physical_name_btn,
                        "args":      "RoutedEventArgs",
                        "todo":      "",
                        "synthetic": True,
                    })
                    seen_hdlrs.add(synthetic_method)

            # All events → collect handler stubs for code-behind
            for evt_type, evt_val in events.items():
                if not evt_val:
                    continue

                # Dùng physical_name (ASCII) để gen method name, tránh tên Nhật thành handler
                # control.data.physical_name → fallback sang name nếu không có
                raw_physical = ctrl.get("data", {}).get("physical_name", "") or name or ""
                
                # Nếu physical_name là tên Nhật (non-ASCII), tra cứu ui_event_map
                # để tìm vba_handler đã đăng ký cho control này
                if any(ord(c) > 127 for c in raw_physical):
                    # Tra cứu trong ui_event_map: tìm entry có control == name
                    physical_name = raw_physical  # default
                    try:
                        from agents.ui.tool_skeleton import _UI_EVENT_MAP
                        import json as _json
                        if _UI_EVENT_MAP.exists():
                            _reg = _json.loads(_UI_EVENT_MAP.read_text(encoding="utf-8"))
                            _entries = _reg.get(form_name, {})
                            cs_suffix = {
                                "onclick": "Click", "ondblclick": "DblClick",
                                "afterupdate": "AfterUpdate", "onkeydown": "PreviewKeyDown",
                            }.get(evt_type, evt_type.replace("on","",1).capitalize())
                            for _mid, _entry in _entries.items():
                                if isinstance(_entry, dict) and _entry.get("event") == evt_type:
                                    _ctrl = _entry.get("control", "")
                                    # Match bằng ctrl name hoặc xấp xỉ
                                    if _ctrl and (_ctrl == name or _ctrl in name or name in _ctrl):
                                        physical_name = _entry["vba_handler"].replace(f"_{cs_suffix}", "")
                                        break
                    except Exception:
                        pass
                else:
                    physical_name = raw_physical

                # Macro reference events: vẫn cần gen event_handler
                # để tool_skeleton tạo stub trong code-behind và cs_stub trong input JSON
                is_macro = evt_val.startswith("macro.")
                if is_macro:
                    # Dùng physical_name để gen method name — KHÔNG dùng tên Nhật (name)
                    method = f"{physical_name}_{evt_type.replace('on','',1).capitalize()}"
                else:
                    # Derive C# method name from VBA handler name
                    # Nếu evt_val đã có underscore (e.g. "施工店情報_DblClick") → dùng thẳng
                    # Nhưng nếu bắt đầu bằng tên Nhật → replace bằng physical_name
                    if "_" in evt_val:
                        # Kiểm tra nếu phần trước underscore là tên Nhật (non-ASCII)
                        base_part = evt_val.split("_")[0]
                        if any(ord(c) > 127 for c in base_part):
                            # Tên Nhật → thay bằng physical_name
                            suffix = "_".join(evt_val.split("_")[1:])
                            method = f"{physical_name}_{suffix}"
                        else:
                            method = evt_val
                    else:
                        method = f"{physical_name}_{evt_type.replace('on','',1).capitalize()}"

                args = EVENT_ARGS.get(evt_type, "RoutedEventArgs")

                if method not in seen_hdlrs:
                    event_handlers.append({
                        "method":   method,
                        "event":    evt_type,
                        "control":  name,
                        "wpf_type": wpf_type,   # needed by gen_codebehind has_pw detection
                        "args":     args,
                        "todo":     "",
                    })
                    seen_hdlrs.add(method)

                # onclick/ondblclick → add Command (kể cả macro events)
                # Macro events vẫn cần Command để code-behind delegate về ViewModel
                if evt_type in ("onclick", "ondblclick"):
                    handler_base = (method
                                    .replace("_Click", "")
                                    .replace("_DblClick", "")
                                    .replace("_Dbl", ""))
                    # Nếu control là Button và handler bắt đầu bằng tên control → dùng stripped name
                    # VD: control=cmdLogin, handler=cmdLogin_Click → base=cmdLogin → LoginCommand
                    if wpf_type == "Button" and handler_base == physical_name and physical_name.startswith("cmd"):
                        handler_base = physical_name.replace("cmd", "", 1)
                    cmd = handler_base + "Command"
                    if cmd not in seen_cmds:
                        commands.append(cmd)
                        seen_cmds.add(cmd)

        return {
            "properties":     properties,
            "commands":       commands,
            "event_handlers": event_handlers,
            "query_stubs":    _stubs,   # contract cho Logic Agent
        }

