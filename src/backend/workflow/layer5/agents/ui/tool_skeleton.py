_CLOSE_BASE_RE = re.compile(r"(?i)^(?:cmd|btn|lbl)?(?:close|quit|exit|閉じる|終了)")


def _load_macro_jp_to_en() -> dict[str, str]:
    """Load listMacroJpToEn.json → {access_macro_name: .NET workflow type name}."""
    if not _MACRO_JP_TO_EN_PATH.exists():
        return {}
    try:
        data = json.loads(_MACRO_JP_TO_EN_PATH.read_text(encoding="utf-8"))
        # graphview writes `wpf_service_ui_name`; older files used `suggested_dotnet_type_name`
        return {
            item["access_macro_name"]: dotnet_type
            for item in data.get("items", [])
            if item.get("access_macro_name")
            and (dotnet_type := item.get("wpf_service_ui_name") or item.get("suggested_dotnet_type_name"))
        }
    except Exception as exc:
        logger.warning("[SkeletonTool] Failed to load listMacroJpToEn.json: %s", exc)
        return {}


def _detect_macro_di_services(form_name: str) -> list[dict]:
    """
    Tự động detect macro workflow services cần inject vào ViewModel.

    Quy trình:
      1. Đọc ui_event_map.json → tìm entries có _note chứa "参照マクロ: MacroName"
      2. Đọc F_Login.json (BD events) → tìm events có notes "参照マクロ: ..."
      3. Map macro name → dotnet type qua listMacroJpToEn.json
      4. Kiểm tra class tồn tại trong WPF Services/ folder
      5. Trả về list DI service cần inject: [{iface, field, param, vm_call}]

    Returns:
        list of dicts: [
          {
            "iface":   "IAMenuBarShowMacroWorkflow",
            "field":   "_aMenuBarShow",
            "param":   "aMenuBarShow",
            "vm_call": "await _aMenuBarShow.ExecuteAsync();",
            "module_ids": ["F006"],  # F-IDs dùng service này
          }, ...
        ]
    """
    macro_jp_to_en = _load_macro_jp_to_en()
    if not macro_jp_to_en:
        return []

    # Collect macro references from ui_event_map.json for this form
    # Entries có _note = "参照マクロ: MacroName.xlsx" hoặc "参照マクロ: MacroName"
    macro_refs: dict[str, list[str]] = {}  # macro_name → [module_ids]

    if _UI_EVENT_MAP.exists():
        try:
            registry = json.loads(_UI_EVENT_MAP.read_text(encoding="utf-8"))
            form_entries = registry.get(form_name, {})
            for module_id, entry in form_entries.items():
                if not isinstance(entry, dict):
                    continue
                note = entry.get("_note", "")
                # "参照マクロ: A_メニューバーを表示.xlsx" → "A_メニューバーを表示"
                ref_name = macro_name(note)
                if ref_name:
                    macro_refs.setdefault(ref_name, []).append(module_id)
        except Exception as exc:
            logger.debug("[SkeletonTool] ui_event_map macro scan failed: %s", exc)

    # Also scan BD events from logic inputs if available
    _bd_input = (
        Path(__file__).resolve().parent.parent  # → agents/
        / "logic" / "inputs" / f"{form_name}_ui.json"
    )
    if _bd_input.exists():
        try:
            ui_data = json.loads(_bd_input.read_text(encoding="utf-8"))
            for evt in ui_data.get("events", []):
                meta = evt.get("event_meta", {})
                notes = meta.get("notes", "")
                module_id = meta.get("module_id", "")
                ref_name = macro_name(notes)
                if ref_name and module_id:
                    if module_id not in macro_refs.get(ref_name, []):
                        macro_refs.setdefault(ref_name, []).append(module_id)
        except Exception as exc:
            logger.debug("[SkeletonTool] logic input macro scan failed: %s", exc)

    if not macro_refs:
        return []

    result: list[dict] = []
    seen_types: set[str] = set()

    for ref_name, module_ids in macro_refs.items():
        dotnet_type = macro_jp_to_en.get(ref_name)
        if not dotnet_type:
            logger.debug("[SkeletonTool] No dotnet type for macro: %s", ref_name)
            continue

        # Check class exists in WPF Services/ folder
        svc_file = _WPF_SERVICES_DIR / f"{dotnet_type}.cs"
        if not svc_file.exists():
            logger.debug("[SkeletonTool] Service file not found: %s", svc_file.name)
            continue

        if dotnet_type in seen_types:
            # Already added — just update module_ids
            for di in result:
                if di.get("dotnet_type") == dotnet_type:
                    di["module_ids"].extend(module_ids)
            continue

        seen_types.add(dotnet_type)

        # Build field/param names: AMenuBarShowMacroWorkflow → _aMenuBarShow / aMenuBarShow
        # Strip "MacroWorkflow" suffix → base name
        base = dotnet_type.replace("MacroWorkflow", "").replace("Workflow", "")
        # camelCase field: AMenuBarShow → _aMenuBarShow
        field = "_" + base[0].lower() + base[1:] if base else "_macro"
        param = base[0].lower() + base[1:] if base else "macro"

        iface = f"I{dotnet_type}"
        vm_call = f"        await {field}.ExecuteAsync();"

        result.append({
            "iface":      iface,
            "field":      field,
            "param":      param,
            "dotnet_type": dotnet_type,
            "macro_name": ref_name,
            "vm_call":    vm_call,
            "module_ids": list(module_ids),
        })
        logger.info(
            "[SkeletonTool] Macro DI detected: %s → %s (modules: %s)",
            ref_name, iface, module_ids,
        )

    return result


def load_service_contract(form_name: str) -> dict:
    """
    Load service contract produced by Agent Service.
    Tries {form_name}.json first (new canonical name), then service_contract.json (legacy).

    Returns the contract dict, or {} if not found.
    """
    _db_dir = SERVICE_CONTRACT_BACKUP_DIR   # written by Agent Service next to its outputs
    _svc_dir = _SERVICE_OUTPUTS_DIR / form_name

    # Priority order: new name first, then legacy
    _candidates = [
        _db_dir / f"{form_name}.json",
        _svc_dir / f"{form_name}.json",
        _db_dir / "service_contract.json",
        _svc_dir / "service_contract.json",
    ]
    contract_path = next((p for p in _candidates if p.exists()), None)
    if not contract_path:
        logger.debug("[SkeletonTool] service contract not found for %s", form_name)
        return {}
    try:
        data = json.loads(contract_path.read_text(encoding="utf-8"))
        logger.info("[SkeletonTool] Loaded contract for %s from %s (%d methods)",
                    form_name, contract_path.name, len(data.get("methods", {})))
        return data
    except Exception as exc:
        logger.warning("[SkeletonTool] Failed to load contract for %s: %s", form_name, exc)
        return {}


# ── Shared event naming helpers ─────────────────────────────────────────────

# VBA event name → C# event handler method suffix
_VBA_EVENT_TO_CS_SUFFIX: dict[str, str] = {
    "onclick":      "Click",
    "click":        "Click",
    "ondblclick":   "DblClick",
    "dblclick":     "DblClick",
    "afterupdate":  "AfterUpdate",
    "beforeupdate": "BeforeUpdate",
    "onkeydown":    "KeyDown",
    "onkeyup":      "KeyUp",
    "ongotfocus":   "GotFocus",
    "onlostfocus":  "LostFocus",
    "onopen":       "Open",
    "onload":       "Load",
    "onclose":      "Close",
    "onchange":     "Changed",
}


def _vba_event_to_cs_suffix(vba_event: str) -> str:
    """Map VBA event name → C# handler method suffix (e.g. 'ondblclick' → 'DblClick')."""
    key = vba_event.lower()
    if key in _VBA_EVENT_TO_CS_SUFFIX:
        return _VBA_EVENT_TO_CS_SUFFIX[key]
    # Generic fallback: strip leading "on", capitalize
    stripped = key.removeprefix("on")
    return stripped.capitalize()


def get_cs_handler_name(module_id: str, vba_event: str) -> str:
    """
    Build the C# event handler method name for XAML attribute and code-behind.

    Pattern: ``{ModuleId}_{EventSuffix}``

    Examples:
        get_cs_handler_name("F006", "ondblclick") → "F006_DblClick"
        get_cs_handler_name("F001", "onclick")    → "F001_Click"
        get_cs_handler_name("F003", "afterupdate")→ "F003_AfterUpdate"
    """
    suffix = _vba_event_to_cs_suffix(vba_event)
    return f"{module_id}_{suffix}"


def _resolve_vba_to_module_id_map(
    form_name: str,
    all_vba_handlers: list[str],
) -> dict[str, str]:
    """
    VBA handler → Module ID (F###) without BD context — fallback when no `fid_map` is passed.
    Agent UI calls core.fid_resolver.resolve_and_sync once per run (with BD events) instead.
    """
    return resolve_and_sync(form_name, [HandlerRef(h) for h in all_vba_handlers if h], prune=False)


def _is_close_like(*names: str) -> bool:
    """True for handlers/controls/commands that close the form or quit (cmdClose_Click, btnExit, 閉じる)."""
    return any(n and _CLOSE_BASE_RE.match(n) for n in names)


def _service_ready(form_name: str, svc_methods: dict, svc_iface: str) -> bool:
    """The contract is usable only when it has methods and Agent Service emitted its interface + DTOs."""
    if not (svc_methods and svc_iface):
        return False
    svc_app = _SERVICE_OUTPUTS_DIR / form_name / "Application"
    if not declares_type(svc_iface, [APPLICATION_PROJECT_DIR / "Interfaces", svc_app / "Interfaces"]):
        logger.warning("[SkeletonTool] %s declared in contract but not generated — no service DI", svc_iface)
        return False
    if not declares_namespace(dto_namespace(form_name, "Requests"), [APPLICATION_PROJECT_DIR / "DTOs", svc_app / "DTOs"]):
        logger.warning("[SkeletonTool] %s not generated — no service DI", dto_namespace(form_name, "Requests"))
        return False
    return True


class SkeletonTool:
    """
    Deterministic C# skeleton generator.
    Không LLM, không token, không hallucination.
    """



    # ──────────────────────────────────────────────────────────────
    # 2. ViewModel skeleton  (per-form)
    # ──────────────────────────────────────────────────────────────

    def gen_viewmodel(
        self,
        form_name: str,
        vm_bindings: dict,
        class_name_override: str | None = None,
        fid_map: dict[str, str] | None = None,
    ) -> str:
        """
        Generate {form_name}.cs — ViewModel skeleton.

        Kế thừa ViewModelBase (INPC đã có sẵn).
        Properties: full get/set với SetProperty pattern.
        Commands:   get-only ICommand + VBA annotation comment.
        Không embed RelayCommand / INPC — để ViewModelBase handle.

        Method names: every handler gets `{F-ID}Async` (fid_map: handler → F### from
        core.fid_resolver; resolved here when not passed). The contract's `method_name`
        is only the service call (`await _svc.{method_name}(request)`).

        Service DI injection — only when the contract has methods AND Agent Service generated
        the interface + Request DTOs (otherwise the ViewModel would not compile):
          - Injects constructor param + field declaration
          - Gen method body that calls service with correct Request type

        class_name_override: if provided, use this as the C# class name instead of
                             sanitize_class_name(form_name). Used by agent_ui to inject
                             the English mapped name (e.g. "AMRequestPrintPDFViewModel").
        """
        vm_class = class_name_override if class_name_override else sanitize_class_name(form_name)
        props           = vm_bindings.get("properties", [])
        commands        = vm_bindings.get("commands", [])
        event_handlers  = vm_bindings.get("event_handlers", [])
        query_stubs     = vm_bindings.get("query_stubs", {})

        # ── Load service contract (Agent Service output) ──────────────────
        svc_contract = load_service_contract(form_name)
        svc_iface: str    = svc_contract.get("iface_class", "")    # e.g. "IFLoginService"
        svc_field: str    = svc_contract.get("service_field", "")  # e.g. "_fLoginService"
        svc_param: str    = svc_field.lstrip("_") if svc_field else ""  # ctor param name
        has_service = bool(svc_field and svc_param) and _service_ready(
            form_name, svc_contract.get("methods", {}), svc_iface
        )
        svc_methods: dict[str, dict] = svc_contract.get("methods", {}) if has_service else {}

        # ── Auto-detect macro DI services — build BEFORE method body loop ──
        # Đọc từ ui_event_map.json + listMacroJpToEn.json + WPF Services/ folder
        extra_di_services = _detect_macro_di_services(form_name)

        # Build module_id → vm_call map để gen method body đúng
        # e.g. F006 → "await _aMenuBarShow.ExecuteAsync();"
        _macro_module_vm_call: dict[str, str] = {}
        for _di in extra_di_services:
            for _mid in _di.get("module_ids", []):
                _macro_module_vm_call[_mid] = _di["vm_call"]

        # Build quick lookup: suggested_property → stub entry
        _prop_to_stub: dict[str, dict] = {
            s["suggested_property"]: s
            for s in query_stubs.values()
            if s.get("suggested_property")
        }

        # vba_handler → F-ID (one map per run, see core.fid_resolver) → FXXXAsync
        all_handlers = [h.get("method", "") for h in event_handlers if h.get("method")]
        vba_mid_map: dict[str, str] = (
            dict(fid_map) if fid_map is not None else _resolve_vba_to_module_id_map(form_name, all_handlers)
        )
        vba_vm_map: dict[str, str] = {h: f"{mid}Async" for h, mid in vba_mid_map.items()}

        # Build VBA annotation map: OldCommandName → handler info + module_id
        # Đồng thời build fid_cmd_name: CommandName dùng F-ID thay vì tên Nhật/VBA
        cmd_vba_map: dict[str, dict] = {}
        # Map: old_cmd_key (tên Nhật) → new_cmd_key (F-ID based e.g. "F005Command")
        old_to_fid_cmd: dict[str, str] = {}

        for hdlr in event_handlers:
            method       = hdlr.get("method", "")
            ctrl         = hdlr.get("control", "")
            evt          = hdlr.get("event", "")
            handler_base = (method
                            .replace("_Click", "")
                            .replace("_DblClick", "")
                            .replace("_AfterUpdate", ""))
            # Button: strip "cmd" prefix → canonical name
            if ctrl and ctrl.startswith("cmd") and handler_base == ctrl:
                handler_base = ctrl.replace("cmd", "", 1)
            old_cmd_key = handler_base + "Command"
            module_id = vba_mid_map.get(method, "")
            # Use F-ID as command name if available, else keep old name
            fid_cmd = f"{module_id}Command" if module_id else old_cmd_key
            # Agent UI already remapped `commands` to F-ID names (_remap_commands_to_fid)
            if old_cmd_key in commands or fid_cmd in commands:
                old_to_fid_cmd[old_cmd_key] = fid_cmd
                cmd_vba_map[fid_cmd] = {
                    "control":     ctrl,
                    "event":       evt,
                    "handler":     method,
                    "module_id":   module_id,
                    "vba_cmd_name": old_cmd_key,  # preserve original for XAML binding comment
                }

        # ── Fallback (legacy callers without fid_map): resolve Commands that have NO
        #    event_handler entry from ui_event_map.json. With fid_map the run's map is authoritative.
        if fid_map is None and _UI_EVENT_MAP.exists():
            try:
                _registry: dict = json.loads(_UI_EVENT_MAP.read_text(encoding="utf-8"))
                _form_entries: dict = _registry.get(form_name, {})
                for _mid, _entry in _form_entries.items():
                    if not isinstance(_entry, dict):
                        continue
                    _vba_handler: str = _entry.get("vba_handler", "")
                    if not _vba_handler:
                        continue
                    _base = (_vba_handler
                             .replace("_Click", "")
                             .replace("_DblClick", "")
                             .replace("_AfterUpdate", ""))
                    if _base.startswith("cmd"):
                        _base = _base[3:]
                    _old_cmd_key = _base + "Command"
                    _fid_cmd = f"{_mid}Command" if _mid else _old_cmd_key
                    # Register under FID command name
                    if (_old_cmd_key in commands or _fid_cmd in [old_to_fid_cmd.get(k, k) for k in commands]) \
                            and _fid_cmd not in cmd_vba_map:
                        _evt = _entry.get("event", "onclick")
                        old_to_fid_cmd[_old_cmd_key] = _fid_cmd
                        cmd_vba_map[_fid_cmd] = {
                            "control":     _entry.get("control", _base),
                            "event":       _evt,
                            "handler":     _vba_handler,
                            "module_id":   _mid,
                            "vba_cmd_name": _old_cmd_key,
                        }
            except Exception as _exc:
                logger.warning("[SkeletonTool] fallback cmd_vba_map lookup failed: %s", _exc)

        # ── Remap commands list: replace old JP/VBA names with F-ID names, sort by F-ID ──
        def _fid_sort_key(cmd_name: str) -> tuple[int, str]:
            """Sort FxxxCommand numerically, unknown names go last."""
            import re as _re
            m = _re.match(r'^F(\d+)Command$', cmd_name)
            return (int(m.group(1)), cmd_name) if m else (9999, cmd_name)

        # Remap: LoginCommand stays as-is (readable), JP names → F-ID
        fid_commands: list[str] = []
        seen_fid: set[str] = set()
        for c in commands:
            fid_name = old_to_fid_cmd.get(c, c)
            if fid_name not in seen_fid:
                fid_commands.append(fid_name)
                seen_fid.add(fid_name)
        # Add any FID commands from fallback not yet in list
        for fid_name in cmd_vba_map:
            if fid_name not in seen_fid:
                fid_commands.append(fid_name)
                seen_fid.add(fid_name)

        # Sort by F-ID order
        fid_commands.sort(key=_fid_sort_key)

        # ── Thêm Commands cho TẤT CẢ handlers chưa có trong fid_commands ──
        # F000/F001/F002 (form lifecycle) và F003 (PasswordBox afterupdate)
        # đều cần Command để code-behind forward vào — uniform pattern
        for hdlr in event_handlers:
            method = hdlr.get("method", "")
            if not method or hdlr.get("synthetic"):
                continue
            mid = vba_mid_map.get(method, "")
            if not mid:
                continue
            fid_cmd = f"{mid}Command"
            if fid_cmd not in seen_fid:
                fid_commands.append(fid_cmd)
                seen_fid.add(fid_cmd)
                # Register in cmd_vba_map for constructor init
                if fid_cmd not in cmd_vba_map:
                    cmd_vba_map[fid_cmd] = {
                        "control":   hdlr.get("control", "__form__"),
                        "event":     hdlr.get("event", ""),
                        "handler":   method,
                        "module_id": mid,
                        "vba_cmd_name": fid_cmd,
                    }

        # Re-sort after adding remaining
        fid_commands.sort(key=_fid_sort_key)
        commands = fid_commands

        # ── Commands (declarations only) ──────────────────────────
        cmd_lines: list[str] = []
        for c in commands:
            vba = cmd_vba_map.get(c)
            if vba:
                mid  = vba.get("module_id", "")
                ctrl = vba.get("control", "")
                evt  = vba.get("event", "")
                # Chỉ giữ comment ngắn gọn: F-ID, control, event
                cmd_lines.append(f"    // [{mid}] {ctrl}[{evt}]")
            # Commands are set once in constructor → read-only property is safe
            cmd_lines.append(f"    public ICommand {c} {{ get; }}")
        commands_block = "\n".join(cmd_lines)

        # Tất cả event handlers đều gen FXXXAsync — kể cả Button onclick
        # Button onclick dùng Command binding trong XAML nhưng async method vẫn cần để Logic Agent implement
        _no_async_stub: set[str] = set()  # không skip gì nữa

        method_lines: list[str] = []
        _generated_vm_methods: set[str] = set()  # track which FXXXAsync exist
        _key_param_methods: set[str] = set()     # FXXXAsync(KeyEventArgs? e = null)
        raises_close = False                     # something in the VM raises CloseRequested
        for hdlr in event_handlers:
            method = hdlr.get("method", "")
            if not method: continue
            if method in _no_async_stub:
                continue
            vm_method = vba_vm_map.get(method) or (method + "Async")
            module_id = vba_mid_map.get(method, "")
            module_id_note = module_id or vm_method.replace("Async", "")
            _generated_vm_methods.add(vm_method)

            # ── Gen method body từ service_contract (SERVICE events) ──────
            # hoặc gen UI stub body cho UI events
            svc_entry = svc_methods.get(module_id) if module_id else None

            # Kiểm tra event_class từ service_contract để quyết định gen body
            svc_event_class = svc_entry.get("event_class", "SERVICE") if svc_entry else "SERVICE"

            # Macro event: module_id có trong _macro_module_vm_call → gen macro call trực tiếp
            # Không cần svc_entry — detect từ ui_event_map + listMacroJpToEn
            macro_vm_call = _macro_module_vm_call.get(module_id_note, "")

            if svc_entry and svc_field and svc_iface and svc_event_class == "SERVICE":
                req_class  = svc_entry.get("request_class", f"{module_id}Request")
                req_props  = svc_entry.get("request_props", [])
                svc_method = svc_entry.get("method_name", vm_method)

                # Build request object initializer
                if req_props:
                    prop_inits = ", ".join(f"{p['name']} = {p['name']}" for p in req_props)
                    req_init = f"new {req_class} {{ {prop_inits} }}"
                else:
                    req_init = f"new {req_class}()"

                method_body = (
                    f"        var request = {req_init};\n"
                    f"        var response = await {svc_field}.{svc_method}(request);\n"
                    f"        if (!response.Success)\n"
                    f"        {{\n"
                    f"            // TODO: handle error — response.Message\n"
                    f"        }}"
                )
                method_sig = f"    public virtual async System.Threading.Tasks.Task {vm_method}()"
            elif macro_vm_call:
                # Macro reference event → gen call trực tiếp đến workflow service
                method_sig = f"    public virtual async System.Threading.Tasks.Task {vm_method}()"
                method_body = macro_vm_call
            elif _is_close_like(method.rsplit("_", 1)[0], hdlr.get("control", "")) and not svc_entry:
                # Close / quit button: works before Agent Logic fills the body (DoCmd.Close)
                method_sig = f"    public virtual async System.Threading.Tasks.Task {vm_method}()"
                method_body = (
                    "        CloseRequested?.Invoke(this, EventArgs.Empty);\n"
                    "        await System.Threading.Tasks.Task.CompletedTask;"
                )
                raises_close = True
            elif svc_entry and svc_event_class == "UI":
                # UI event — có stub signature tùy chỉnh không?
                custom_sig = svc_entry.get("vm_signature", "")
                if custom_sig:
                    params_match = re.search(r'\(([^)]*)\)', custom_sig)
                    param_str = params_match.group(1) if params_match else ""
                    method_sig = f"    public virtual async System.Threading.Tasks.Task {vm_method}({param_str})"
                else:
                    method_sig = f"    public virtual async System.Threading.Tasks.Task {vm_method}()"
                method_body = "        // TODO: Logic Agent implements — UI event handler\n        await System.Threading.Tasks.Task.CompletedTask;"
            else:
                # Check if this is a keydown event → needs KeyEventArgs parameter
                _hdlr_event = next(
                    (h.get("event", "") for h in event_handlers if vba_mid_map.get(h.get("method", "")) == module_id_note),
                    ""
                ).lower()
                if _hdlr_event in ("onkeydown", "onkeyup", "onkeypress"):
                    method_sig = f"    public virtual async System.Threading.Tasks.Task {vm_method}(System.Windows.Input.KeyEventArgs? e = null)"
                    _key_param_methods.add(vm_method)
                else:
                    method_sig = f"    public virtual async System.Threading.Tasks.Task {vm_method}()"
                method_body = "        await System.Threading.Tasks.Task.CompletedTask;"

            method_lines.append(
                f"    /// <summary>[{module_id_note}] {method}</summary>\n"
                f"{method_sig}\n"
                f"    {{\n"
                f"{method_body}\n"
                f"    }}"
            )
        methods_block = "\n\n".join(method_lines)

        # ── Command constructor initializations ───────────────────
        def _no_handler_cmd(cmd_name: str, *names: str) -> str:
            nonlocal raises_close
            if _is_close_like(cmd_name.removesuffix("Command"), *names):
                raises_close = True
                return f"        {cmd_name} = Cmd(_ => CloseRequested?.Invoke(this, EventArgs.Empty));"
            return f"        {cmd_name} = Cmd(_ => {{ }});"

        cmd_init_lines: list[str] = []
        for c in commands:
            vba = cmd_vba_map.get(c)
            if not vba:
                cmd_init_lines.append(_no_handler_cmd(c))
                continue
            handler   = vba.get("handler", "")
            vm_method = vba_vm_map.get(handler, "")
            module_id_cmd = vba.get("module_id", "")

            # Kiểm tra xem method này có custom signature không (e.g. F001 có KeyEventArgs)
            svc_entry_cmd = svc_methods.get(module_id_cmd) if module_id_cmd else None
            has_custom_sig = (
                svc_entry_cmd is not None and
                svc_entry_cmd.get("vm_signature", "")
            )
            if vm_method and vm_method in _generated_vm_methods:
                if vm_method in _key_param_methods:
                    # Key events: the code-behind passes the KeyEventArgs as the command parameter
                    cmd_init_lines.append(
                        f"        {c} = Cmd(async p => await {vm_method}(p as System.Windows.Input.KeyEventArgs));"
                    )
                elif has_custom_sig:
                    # Method có param từ vm_signature → forward param từ Command
                    import re as _re
                    param_match = _re.search(r'\(([^)]+)\)', has_custom_sig)
                    if param_match and param_match.group(1).strip():
                        param_type = param_match.group(1).split('?')[0].strip().rsplit(' ', 1)[0]
                        cmd_init_lines.append(
                            f"        {c} = Cmd(async p => await {vm_method}(p as {param_type}));"
                        )
                    else:
                        cmd_init_lines.append(f"        {c} = Cmd(async _ => await {vm_method}());")
                else:
                    cmd_init_lines.append(f"        {c} = Cmd(async _ => await {vm_method}());")
            else:
                # Empty — Logic Agent will implement (close/quit buttons raise CloseRequested)
                cmd_init_lines.append(_no_handler_cmd(c, handler, vba.get("control", "")))
        ctor_cmd_init = "\n".join(cmd_init_lines)

        # ── Properties (PasswordBox + query-bound) ───────────────────────
        prop_lines: list[str] = []

        # Collect all request props from service contract to ensure they're in ViewModel
        # so method bodies like `TxtID = TxtID` compile correctly
        contract_req_props: dict[str, str] = {}  # prop_name → type
        for mid, m_entry in svc_methods.items():
            for rp in m_entry.get("request_props", []):
                pname = rp.get("name", "")
                ptype = rp.get("type", "string")
                if pname and pname not in contract_req_props:
                    contract_req_props[pname] = ptype

        # Merge: start with props from vm_bindings, add any missing contract props
        all_props = list(props)
        existing_lower = {p.lower() for p in all_props}
        for cp_name in contract_req_props:
            if cp_name.lower() not in existing_lower:
                all_props.append(cp_name)
                existing_lower.add(cp_name.lower())

        # The PasswordBox-bound property is named "TxtPass" (Request DTO naming + the AXAML
        # Text binding emitted for the converted PasswordBox). Other "...pass..." names stay.
        pw_source = vm_bindings.get("password_property")
        for idx, p in enumerate(all_props):
            if (p == pw_source) if pw_source else p.lower() in ("pass", "password", "txtpass"):
                all_props[idx] = "TxtPass"

        # Deduplicate all_props (preserving order)
        seen_props = set()
        deduped_props = []
        for p in all_props:
            if p.lower() not in seen_props:
                deduped_props.append(p)
                seen_props.add(p.lower())
        all_props = deduped_props

        # Recalculate lower case checking
        existing_lower = {p.lower() for p in all_props}

        pw_props = [p for p in all_props if p == "TxtPass"]
        pw_props_deduped = list(pw_props)

        for pw_p in pw_props_deduped:
            if pw_p not in _prop_to_stub:
                backing_pw = f"_{pw_p[0].lower()}{pw_p[1:]}"
                prop_lines.append(
                    f"    private string {backing_pw} = string.Empty;\n"
                    f"    public string {pw_p} {{ get => {backing_pw}; set => SetProperty(ref {backing_pw}, value); }}"
                )

        for p in all_props:
            if p in pw_props:
                continue
            stub = _prop_to_stub.get(p)
            if stub:
                table = stub.get("table", "")
                field_label = stub.get("field_en", stub.get("field", ""))
                backing = f"_{p[0].lower()}{p[1:]}"
                prop_lines.append(
                    f"    // [QUERY] {field_label} from {table}\n"
                    f"    private string {backing} = string.Empty;\n"
                    f"    public string {p} {{ get => {backing}; set => SetProperty(ref {backing}, value); }}"
                )
            else:
                cs_type = contract_req_props.get(p, "string")
                backing = f"_{p[0].lower()}{p[1:]}"
                default = "string.Empty" if cs_type == "string" else "default!"
                prop_lines.append(
                    f"    private {cs_type} {backing} = {default};\n"
                    f"    public {cs_type} {p} {{ get => {backing}; set => SetProperty(ref {backing}, value); }}"
                )

        props_section = (
            "\n    // ─ Properties ──\n"
            + "\n\n".join(prop_lines)
            + "\n"
        ) if prop_lines else ""

        commands_section = (
            "\n    // ─ Commands ──\n"
            f"{commands_block}\n"
        ) if commands else ""

        # ── CloseRequested event — standard MVVM window close pattern ────────
        # Luôn inject vào mọi ViewModel: Logic Agent dùng để close window từ ViewModel
        # Code-behind subscribe: vm.CloseRequested += (_, _) => Close();
        close_event_section = (
            "\n    /// <summary>ウィンドウを閉じる要求イベント (DoCmd.Close相当)。</summary>\n"
            "    public event EventHandler? CloseRequested;\n"
        )
        if not raises_close:
            close_event_section += (
                "\n    /// <summary>View に CloseRequested を通知する (DoCmd.Close相当)。</summary>\n"
                "    protected void RequestClose() => CloseRequested?.Invoke(this, EventArgs.Empty);\n"
            )

        # ── DI field + constructor ────────────────────────────────────────
        # extra_di_services / _macro_module_vm_call already built above (before method body loop)

        if has_service:
            # Build DI fields: primary service + extra workflow services
            di_field_lines = [f"    private readonly {svc_iface} {svc_field};"]
            ctor_params = [f"{svc_iface} {svc_param}"]
            ctor_assignments = [f"        {svc_field} = {svc_param};"]

            for di in extra_di_services:
                di_iface = di.get("iface", "")
                di_field_name = di.get("field", "")
                di_param_name = di.get("param", "")
                if di_iface and di_field_name and di_param_name:
                    di_field_lines.append(f"    private readonly {di_iface} {di_field_name};")
                    ctor_params.append(f"{di_iface} {di_param_name}")
                    ctor_assignments.append(f"        {di_field_name} = {di_param_name};")

            di_field = "\n".join(di_field_lines) + "\n"
            ctor_param_str = ",\n        ".join(ctor_params)
            ctor_body = "\n".join(ctor_assignments) + "\n"
            if ctor_cmd_init:
                ctor_body += ctor_cmd_init + "\n"

            # Multi-param constructor: wrap params nếu có nhiều hơn 1
            if len(ctor_params) > 1:
                ctor_section = (
                    f"\n{di_field}"
                    f"\n    public {vm_class}(\n        {ctor_param_str})\n"
                    f"    {{\n"
                    f"{ctor_body}"
                    f"    }}\n"
                )
            else:
                ctor_section = (
                    f"\n{di_field}"
                    f"\n    public {vm_class}({svc_iface} {svc_param})\n"
                    f"    {{\n"
                    f"{ctor_body}"
                    f"    }}\n"
                )
        elif extra_di_services:
            # Không có service contract, nhưng có macro DI services → inject chúng
            di_field_lines = []
            ctor_params = []
            ctor_assignments = []

            for di in extra_di_services:
                di_iface = di.get("iface", "")
                di_field_name = di.get("field", "")
                di_param_name = di.get("param", "")
                if di_iface and di_field_name and di_param_name:
                    di_field_lines.append(f"    private readonly {di_iface} {di_field_name};")
                    ctor_params.append(f"{di_iface} {di_param_name}")
                    ctor_assignments.append(f"        {di_field_name} = {di_param_name};")

            di_field = "\n".join(di_field_lines) + "\n" if di_field_lines else ""
            ctor_param_str = ",\n        ".join(ctor_params)
            ctor_body = "\n".join(ctor_assignments) + "\n"
            if ctor_cmd_init:
                ctor_body += ctor_cmd_init + "\n"

            ctor_section = (
                f"\n{di_field}"
                f"\n    public {vm_class}(\n        {ctor_param_str})\n"
                f"    {{\n"
                f"{ctor_body}"
                f"    }}\n"
            )
        elif commands and ctor_cmd_init:
            ctor_section = (
                f"\n    public {vm_class}()\n"
                f"    {{\n"
                f"{ctor_cmd_init}\n"
                f"    }}\n"
            )
        else:
            ctor_section = ""

        methods_section = (
            "\n    #region Methods (Logic Agent implements)\n"
            f"    {methods_block}\n"
            "    #endregion\n"
        ) if method_lines else ""

        # ── using directives — add service namespace if needed ────────────
        extra_usings_list = []
        if extra_di_services:
            extra_usings_list.append("using vba_brain.UI.WPF.Services;")
        if has_service:
            extra_usings_list.append("using vba_brain.Application.Interfaces;")
            dto_roots = [APPLICATION_PROJECT_DIR / "DTOs", _SERVICE_OUTPUTS_DIR / form_name / "Application" / "DTOs"]
            for kind in ("Requests", "Responses"):
                ns = dto_namespace(form_name, kind)
                if kind == "Requests" or declares_namespace(ns, dto_roots):
                    extra_usings_list.append(f"using {ns};")
        if _key_param_methods:
            extra_usings_list.append("using Avalonia.Input;")   # Key / KeyEventArgs in key handlers

        extra_usings = ""
        if extra_usings_list:
            extra_usings = "\n" + "\n".join(extra_usings_list)

        return f"""\
using System.Windows.Input;
using vba_brain.UI.WPF.Utils;{extra_usings}

namespace vba_brain.UI.WPF.ViewModels;

/// <summary>
/// {form_name}のViewModel。
/// </summary>
public class {vm_class} : ViewModelBase
{{
{props_section}{close_event_section}{commands_section}{ctor_section}{methods_section}}}
"""

    # ──────────────────────────────────────────────────────────────
    # 3. Code-behind skeleton  (per-form)
    # ──────────────────────────────────────────────────────────────

    def gen_codebehind(
        self,
        form_name: str,
        vm_bindings: dict,
        class_name_override: str | None = None,
        vm_class_name_override: str | None = None,
        fid_map: dict[str, str] | None = None,
        control_events: list[tuple[str, str, str]] | None = None,
    ) -> str:
        """
        Generate {View}.axaml.cs — MVVM code-behind (no named event handlers).

        - Public parameterless constructor (XAML loader / previewer, Avalonia AVLN3001) that only
          calls InitializeComponent(); the view-model constructor chains `: this()`.
        - Form lifecycle events → inline lambdas forwarding to the F-ID commands
          (Avalonia-unsupported Access form events become a TODO comment, never a raw VBA name).
        - control_events: (x:Name, Avalonia event, F###Command) wiring for non-Button controls —
          Avalonia has no Interaction.Triggers, so `<i:InvokeCommandAction>` blocks become this.
        - viewModel.CloseRequested closes the window.

        class_name_override:    if provided, use as the C# partial class name (e.g. "AMRequestPrintPDFView").
        vm_class_name_override: if provided, use as the ViewModel parameter type (e.g. "AMRequestPrintPDFViewModel").
                                Defaults to class_name_override (without "View" suffix + "ViewModel") if not set.
        """
        class_name = class_name_override if class_name_override else sanitize_class_name(form_name)

        # Derive ViewModel class name:
        # 1. Explicit override (most precise)
        # 2. If class_name ends with "View" → strip + append "ViewModel"
        # 3. Fallback: same as class_name
        if vm_class_name_override:
            vm_class_name = vm_class_name_override
        elif class_name.endswith("View"):
            vm_class_name = class_name + "Model"       # "AMRequestPrintPDFView" → "AMRequestPrintPDFViewModel"
        else:
            vm_class_name = class_name
        event_handlers: list[dict] = vm_bindings.get("event_handlers", [])

        # Build: vba_handler → module_id (e.g. "プロセス終了_DblClick" → "F009")
        all_handlers = [h.get("method", "") for h in event_handlers if h.get("method")]
        vba_mid_map: dict[str, str] = (
            dict(fid_map) if fid_map is not None else _resolve_vba_to_module_id_map(form_name, all_handlers)
        )

        # Form lifecycle events → inline lambda: Loaded += (_, _) => viewModel.F000Command.Execute(null);
        ctor_wiring_lines: list[str] = []
        for hdlr in (h for h in event_handlers if h.get("control") == "__form__"):
            vba_method = hdlr.get("method", "")
            module_id = vba_mid_map.get(vba_method, "") if vba_method else ""
            if not module_id:
                continue
            fid_cmd = f"{module_id}Command"
            wpf_event = hdlr.get("wpf_event", "")
            if wpf_event not in _WINDOW_EVENTS:
                ctor_wiring_lines.append(
                    f"        // TODO: Access form event '{hdlr.get('event', '')}' ({vba_method}) has no "
                    f"Avalonia equivalent — execute viewModel.{fid_cmd} where appropriate."
                )
            elif wpf_event in _KEY_EVENTS:
                # Key events pass the KeyEventArgs for e.Key / e.Handled
                ctor_wiring_lines.append(f"        {wpf_event} += (_, e) => viewModel.{fid_cmd}.Execute(e);")
            else:
                ctor_wiring_lines.append(f"        {wpf_event} += (_, _) => viewModel.{fid_cmd}.Execute(null);")

        for ctrl_name, avalonia_event, cmd in control_events or []:
            ctor_wiring_lines.append(f"        {ctrl_name}.{avalonia_event} += (_, _) => viewModel.{cmd}.Execute(null);")

        ctor_wiring = ("\n" + "\n".join(ctor_wiring_lines)) if ctor_wiring_lines else ""

        return f"""\
using Avalonia.Controls;

namespace vba_brain.UI.WPF.Views;

/// <summary>
/// {form_name} のコードビハインド — MVVM 準拠。
/// </summary>
public partial class {class_name} : Window
{{
    /// <summary>Used by the XAML loader and previewer; the app builds the view with its view model.</summary>
    public {class_name}()
    {{
        InitializeComponent();
    }}

    public {class_name}(ViewModels.{vm_class_name} viewModel) : this()
    {{
        DataContext = viewModel;{ctor_wiring}
        viewModel.CloseRequested += (_, _) => Close();
    }}
}}
"""
