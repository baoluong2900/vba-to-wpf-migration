def _jp_to_en_items(*relative_paths: str) -> list[dict]:
    """Items of graphview JP→EN maps (outputs/<relative path>), in the given order."""
    items: list[dict] = []
    for rel in relative_paths:
        path = _GRAPHVIEW_OUTPUTS / rel
        if not path.exists():
            continue
        try:
            items.extend(json.loads(path.read_text(encoding="utf-8")).get("items", []))
        except (OSError, ValueError) as e:
            logger.warning("[tool_report] Failed to parse %s: %s", path.name, e)
    return items


def is_report_document(form_name: str, mongo_form: dict | None = None, dd_json: dict | None = None) -> bool:
    """Report vs form: Layer 1 document type (forms.type 'Reports'), then the graphview report map, then the 'R' prefix."""
    for doc in (mongo_form or {}, dd_json or {}):
        doc_type = str(doc.get("type") or doc.get("object_type") or doc.get("category") or "").strip().lower()
        if doc_type in ("report", "reports"):
            return True
        if doc_type in ("form", "forms"):
            return False
    if any(item.get("access_form_name") == form_name for item in _jp_to_en_items("reports/listReportJpToEn.json")):
        return True
    return form_name.startswith("R")


def get_english_report_name(form_name: str) -> str:
    """EN stem of a report from the graphview maps (reports, then forms); the sanitized name otherwise."""
    for item in _jp_to_en_items("reports/listReportJpToEn.json", "forms/listFormJpToEn.json"):
        if item.get("access_form_name") == form_name:
            v_name = item.get("wpf_view_name")
            if v_name:
                return v_name[:-4] if v_name.endswith("View") else v_name
    return cs_identifier(form_name, fallback="Report")


def find_companion_report_name(form_name: str) -> str:
    """Companion report (e.g. R005_...) referenced by this form's input snapshot; '' when there is none."""
    json_path = INPUTS_DIR / f"{form_name}_report_input.json"
    if not json_path.exists():
        json_path = INPUTS_DIR / f"{form_name}.json"

    raw_text = ""
    if json_path.exists():
        raw_text = json_path.read_text(encoding="utf-8")

    # Match [refer: R...] pattern
    pattern = r'\[refer:\s*(R[a-zA-Z0-9_\u3000-\u303F\u3040-\u309F\u30A0-\u30FF\uFF00-\uFFEF\u4E00-\u9FAF_]+)\]'
    matches = re.findall(pattern, raw_text)

    if matches:
        extracted = matches[0].strip()

        # Try to resolve actual report file in inputs/ folder
        for p in INPUTS_DIR.glob("R*.json"):
            stem = p.stem.replace("_report_input", "").replace("_dd", "").replace("_bd", "")
            if stem == extracted:
                return stem

        return extracted

    return ""


def parse_pdf_output_vba(vba_code: str) -> dict:
    """Parse VBA code for PDF output to extract metadata."""
    msg = ""
    folder_name = ""
    report_name = ""
    filename_pattern = ""

    # Extract MsgBox message
    msg_match = re.search(r'MsgBox\s+"([^"]+)"', vba_code or "", re.IGNORECASE)
    if msg_match:
        msg = msg_match.group(1)

    # Extract FolderName
    folder_match = re.search(r'FolderName\s*=\s*"([^"]+)"', vba_code or "", re.IGNORECASE)
    if folder_match:
        folder_name = folder_match.group(1)

    # Extract Report Name
    report_match = re.search(r'acOutputReport\s*,\s*"([^"]+)"', vba_code or "", re.IGNORECASE)
    if report_match:
        report_name = report_match.group(1)

    # Extract Filename pattern, e.g. FolderName & "\" & Format(Now, "yyyymmdd-hhnn") & "_作業報告書_支店施工管理" & ".pdf"
    pattern_match = re.search(r'FolderName\s*&\s*"\\"\s*&\s*(.*?)\s*&\s*"\.pdf"', vba_code or "", re.IGNORECASE)
    if pattern_match:
        filename_pattern = pattern_match.group(1).strip()

    return {
        "msg": msg,
        "folder_name": folder_name,
        "report_name": report_name,
        "filename_pattern": filename_pattern
    }


def _pdf_file_name_expr(filename_pattern: str, report_stem: str) -> str:
    """C# interpolated string for the PDF file name: Format(Now, "yyyymmdd-hhnn") & "_suffix" → $"{Now:...}_suffix.pdf"."""
    cs_fmt, suffix = "yyyyMMdd-HHmm", f"_{report_stem}"
    fmt_match = re.search(r'Format\(Now\s*,\s*"([^"]+)"\)', filename_pattern or "")
    if fmt_match:
        # Map vba format to C# datetime format
        cs_fmt = fmt_match.group(1).replace("mm", "MM").replace("hh", "HH").replace("nn", "mm")
        suffix_match = re.search(r'&\s*"([^"]+)"', filename_pattern)
        suffix = suffix_match.group(1) if suffix_match else ""
    suffix = _cs_string(suffix).replace("{", "{{").replace("}", "}}")
    return f'$"{{System.DateTime.Now.ToString("{_cs_string(cs_fmt)}")}}{suffix}.pdf"'


def generate_pdf_click_csharp(vba_code: str, form_name: str, handler_name: str, english_companion_report: str,
                              data_hint: str = "") -> str:
    """Avalonia-safe PDF handler: output path from the VBA; rendering is a TODO (no RDLC renderer for .NET 10)."""
    meta = parse_pdf_output_vba(vba_code)
    if meta["report_name"]:
        english_report = get_english_report_name(meta["report_name"])
    else:
        english_report = english_companion_report or get_english_report_name(form_name)
    msg_line = f'        System.Diagnostics.Debug.WriteLine("{_cs_string(meta["msg"])}");\n' if meta["msg"] else ""
    return (
        f"    /// <summary>[{handler_name}] {handler_name}</summary>\n"
        f"    public virtual async System.Threading.Tasks.Task {handler_name}Async()\n"
        "    {\n"
        f"        // TODO(report): render Views/Reports/{english_report}Report.rdlc to PDF. There is no RDLC\n"
        "        //   renderer for Avalonia/.NET 10 — produce the PDF with a PDF library from the report rows.\n"
        f"        //   Data: {data_hint or 'see the form service contract'}\n"
        f"{msg_line}"
        "        var folder = System.IO.Path.Combine(\n"
        "            System.Environment.GetFolderPath(System.Environment.SpecialFolder.Desktop),\n"
        f'            "{_cs_string(meta["folder_name"])}");\n'
        f"        var fullPath = System.IO.Path.Combine(folder, {_pdf_file_name_expr(meta['filename_pattern'], english_report)});\n"
        '        System.Diagnostics.Debug.WriteLine($"PDF export not implemented yet: {fullPath}");\n'
        "        await System.Threading.Tasks.Task.CompletedTask;\n"
        "    }"
    )


