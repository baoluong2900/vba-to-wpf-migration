def twips_to_pixels(twips: Any) -> float:
    """Convert twips to device-independent pixels (1 twip = 1/15 pixels)."""
    try:
        return round(float(twips) / 15.0, 1)
    except:
        return 0.0


# Access stores Windows system colours as 0x80000000 | GetSysColor index (negative ints).
_SYSTEM_COLORS = {
    0x05: "#FFFFFF",  # COLOR_WINDOW (window background)
    0x08: "#000000",  # COLOR_WINDOWTEXT
    0x0F: "#F0F0F0",  # COLOR_BTNFACE
    0x12: "#000000",  # COLOR_BTNTEXT
}
_DEFAULT_SYSTEM_COLOR = "#A6A6A6"  # e.g. -2147483617, Access' default border grey


def access_color_to_hex(color_val: Any, backstyle: Any = 1) -> str:
    """Access colour (BGR int, or negative system colour) → #RRGGBB; Transparent when backstyle is 0."""
    if str(backstyle).strip() == "0":
        return "Transparent"
    if color_val is None:
        return "#000000"
    try:
        val = int(color_val)
    except (TypeError, ValueError):
        return "#000000"
    if val < 0:
        return _SYSTEM_COLORS.get(val & 0xFF, _DEFAULT_SYSTEM_COLOR)
    # OLE color is BGR format
    r = val & 0xFF
    g = (val >> 8) & 0xFF
    b = (val >> 16) & 0xFF
    return f"#{r:02X}{g:02X}{b:02X}"


def textalign_mapping(align: Any) -> str:
    """Map Access textalign to WPF TextAlignment."""
    try:
        a = int(align)
        if a == 1: return "Left"
        if a == 2: return "Center"
        if a == 3: return "Right"
        return "Default"
    except:
        return "Default"


def _rdlc_field(name: str) -> str:
    """RDLC DataSet field name (CLS identifier: starts with a letter; Japanese letters are fine)."""
    ident = cs_identifier(name or "", fallback="Field")
    return ident if not ident.startswith("_") else ("F" + ident.lstrip("_") if ident.strip("_") else "Field")


def _rdlc_item_name(candidate: str, itype: str, idx: int, used: set) -> str:
    """Unique ReportItem name: ASCII letters/digits/'_' starting with a letter (RDLC rejects duplicates)."""
    name = re.sub(r"_+", "_", re.sub(r"[^A-Za-z0-9_]", "_", candidate or "")).strip("_")
    if not name or not name[0].isalpha():
        prefix = re.sub(r"[^A-Za-z]", "", itype or "") or "Item"
        name = f"{prefix}{idx}" + (f"_{name}" if name else "")
    unique, n = name, 1
    while unique in used:
        n += 1
        unique = f"{name}_{n}"
    used.add(unique)
    return unique


def _cs_string(value: str) -> str:
    """Escape text for a regular C# string literal."""
    return (value or "").replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n")


def clean_field_name(source: str) -> str:
    """Clean the raw Japanese control source string into a clean field name, extracting from Format/Nz functions."""
    if not source:
        return ""
    
    cleaned = source.strip().lstrip('=')
    
    # 1. Try to extract from standard function wrappers Format(field, ...) or Nz(field, ...)
    format_match = re.match(r'(?i)Format\(\s*\[?([^,\)]+)\]?\s*,\s*[^)]+\)', cleaned)
    if format_match:
        cleaned = format_match.group(1)
    else:
        nz_match = re.match(r'(?i)Nz\(\s*\[?([^,\)]+)\]?\s*,\s*[^)]+\)', cleaned)
        if nz_match:
            cleaned = nz_match.group(1)
            
    # 2. Extract first bracketed field if multiple brackets or concatenated expression (e.g. [Field] & "様")
    brackets = re.findall(r'\[([^\]]+)\]', cleaned)
    if brackets:
        cleaned = brackets[0]
        
    # 3. Strip remaining brackets and quotes
    cleaned = cleaned.replace('[', '').replace(']', '').replace('"', '').replace("'", "")
    
    # 4. Remove any table alias prefix (e.g. T_Table.Field -> Field)
    cleaned = cleaned.split('.')[-1]
    
    return cleaned.strip()

