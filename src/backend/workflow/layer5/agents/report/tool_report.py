def patch_existing_ui(form_name: str, mongo_procedures: list[dict] | None = None) -> list[GeneratedFile]:
    """
    Fill the report handlers (PDF / print / close) of the Avalonia ViewModel generated by agent_ui.

    There is no RDLC renderer for Avalonia/.NET 10, so PDF and print get a TODO body naming the
    companion .rdlc and the service call (from the service contract) that supplies its rows; close
    uses the Avalonia application lifetime. Service calls themselves are generated by agent_logic.
    """
    generated_files: list[GeneratedFile] = []

    companion_report = find_companion_report_name(form_name)
    english_companion_report = get_english_report_name(companion_report or form_name)
    logger.info("[tool_report] Companion report: %s -> %s for %s", companion_report or "(none)", english_companion_report, form_name)

    _, vm_name_stem = _resolve_view_names(form_name)
    vm_path = WPF_PROJECT_DIR / "ViewModels" / f"{vm_name_stem}.cs"
    if not vm_path.exists():
        logger.warning("[tool_report] ViewModel not found for %s (%s) — run agent_ui first", form_name, vm_path)
        return generated_files

    content = vm_path.read_text(encoding="utf-8")
    data_hint = _report_data_hint(load_service_contract(form_name))
    patch_state = _load_patch_state()
    state = patch_state.setdefault(form_name, {})

    def apply(handler: str, implementation: str) -> None:
        # Replace the previous patch (idempotent re-runs) or agent_ui's empty stub
        nonlocal content
        for old in (state.get(f"{handler}Async"), _handler_placeholder(handler)):
            if old:
                content = _safe_replace(content, old, implementation)
        state[f"{handler}Async"] = implementation

    content = content.replace('PDF出力Command = Cmd(_ => { });', 'PDF出力Command = Cmd(async _ => await PDF出力_ClickAsync());')
    content = content.replace('印刷するCommand = Cmd(_ => { });', '印刷するCommand = Cmd(async _ => await 印刷する_ClickAsync());')
    content = content.replace('閉じるCommand = Cmd(_ => { });', '閉じるCommand = Cmd(async _ => await 閉じる_ClickAsync());')

    pdf_procs = [
        proc for proc in mongo_procedures or []
        if "PDF出力" in (proc.get("handler") or "") and (proc.get("handler") or "").endswith("_Click")
    ]
    for proc in pdf_procs:
        apply(proc["handler"], generate_pdf_click_csharp(proc.get("code", ""), form_name, proc["handler"],
                                                         english_companion_report, data_hint))
    if not pdf_procs:
        apply("PDF出力_Click", generate_pdf_click_csharp("", form_name, "PDF出力_Click", english_companion_report, data_hint))
    apply("印刷する_Click", _print_implementation(english_companion_report, data_hint))
    apply("閉じる_Click", _CLOSE_IMPLEMENTATION)

    _save_patch_state(patch_state)
    generated_files.append(GeneratedFile(
        path=f"ViewModels/{vm_path.name}",
        content=content,
        generator="patch_viewmodel",
        agent="report"
    ))
    return generated_files

