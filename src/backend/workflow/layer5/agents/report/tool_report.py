def load_service_contract(form_name: str) -> dict:
    """Agent Service contract of a form (agents/service/outputs/{form}/{form}.json); {} when absent."""
    svc_dir = BASE_DIR.parent / "service" / "outputs" / form_name
    for path in (svc_dir / f"{form_name}.json", svc_dir / "service_contract.json"):
        if path.exists():
            try:
                return json.loads(path.read_text(encoding="utf-8"))
            except (OSError, ValueError) as e:
                logger.warning("[tool_report] Unreadable service contract %s: %s", path, e)
    return {}


def _report_data_hint(contract: dict) -> str:
    """'IXService.F000Async(F000Request) → F000Response.Data' for the first service method returning rows."""
    iface = contract.get("iface_class") or "the form service"
    for method in (contract.get("methods") or {}).values():
        rows = [p.get("name") for p in method.get("response_props") or [] if str(p.get("type", "")).startswith("IEnumerable<")]
        if rows:
            return f"{iface}.{method.get('method_name')}({method.get('request_class')}) → {method.get('response_class')}.{rows[0]}"
    return f"{iface} has no method returning report rows yet"


def _resolve_view_names(form_name: str) -> tuple[str, str]:
    """(wpf_view_name, wpf_viewmodel_name) from the graphview maps; the form name when unmapped."""
    for item in _jp_to_en_items("forms/listFormJpToEn.json", "reports/listReportJpToEn.json"):
        if item.get("access_form_name") == form_name:
            return item.get("wpf_view_name") or form_name, item.get("wpf_viewmodel_name") or form_name
    return form_name, form_name


def _safe_replace(content: str, old: str, new: str) -> str:
    if old in content:
        return content.replace(old, new)
    old_rn, new_rn = old.replace("\n", "\r\n"), new.replace("\n", "\r\n")
    if old_rn in content:
        return content.replace(old_rn, new_rn)
    return content


